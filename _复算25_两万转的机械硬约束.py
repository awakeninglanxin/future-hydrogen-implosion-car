import math

def sec(t):
    print("\n" + "=" * 78)
    print(t)
    print("=" * 78)

def ok(t):
    print("  [OK] " + t)

def warn(t):
    print("  [!]  " + t)

print("#" * 78)
print("#  _复算25 · 20000 rpm / 60 rpm / 死飞限制")
print("#" * 78)

# ============================================================
# 参数：以一台典型车用直喷柴油机为基准（4.8 L 级，与 JCB 448 同量级）
# ============================================================
BORE = 0.106           # m  缸径
STROKE = 0.135         # m  冲程（长冲程柴油机）
ROD = 0.220            # m  连杆长度（≈1.63×冲程）
PISTON_M = 1.75        # kg 活塞组件（活塞+销+环），重型柴油机
FLYWHEEL_R = 0.25      # m  飞轮半径
FLYWHEEL_M = 55.0      # kg 飞轮质量

sec("基准机型参数（4.8 L 级车用柴油机）")
print(f"""
  缸径 × 冲程        = {BORE*1000:.0f} × {STROKE*1000:.0f} mm
  连杆长度 L         = {ROD*1000:.0f} mm  (L/r = {ROD/(STROKE/2):.2f})
  活塞组件质量 m     = {PISTON_M} kg
  飞轮 半径/质量     = {FLYWHEEL_R*1000:.0f} mm / {FLYWHEEL_M:.0f} kg
  ★ 这是**长冲程 + 重活塞**的柴油机典型值（汽油机短冲程、活塞约 1/4 重）
""")

# ============================================================
sec("Q1  活塞平均速度 MPS —— 20000 rpm 意味着什么？")
# ============================================================
print("""
  MPS (Mean Piston Speed) = 2 × 冲程 × 转速(转/秒) = 2·S·N/60
  它是内燃机**最重要的机械负荷指标**，业界有公认区间。
""")
RPM_LIST = [60, 800, 1150, 2000, 4000, 6000, 8000, 12000, 20000]

def mps(rpm, s=STROKE):
    return 2 * s * rpm / 60.0

print(f"  {'转速':>8} | {'MPS':>10} | 参照系")
print("  " + "-" * 68)
MPS_REF = {
    60:    "★ 老师说的最低怠速（活塞几乎'爬行'）",
    800:   "柴油机典型怠速",
    1150:  "JCB 448 额定扭矩点",
    2000:  "柴油机高速巡航",
    4000:  "★ 车用柴油机红线（≈极限）",
    6000:  "仅赛车柴油机可达",
    8000:  "❌ 已超柴油机任何量产记录",
    12000: "❌ 接近汽油赛车极限",
    20000: "❌❌ 老师说的 Joe Cell 装车后转速",
}
for rpm in RPM_LIST:
    v = mps(rpm)
    print(f"  {rpm:>8} | {v:>8.1f} m/s | {MPS_REF[rpm]}")
print("  " + "-" * 68)

print("""
  ★ 业界 MPS 参照（公认工程区间）：
     船用低速柴油机   6 – 9   m/s
     车用柴油机       9 – 14  m/s
     车用汽油机      12 – 18  m/s
     ★ F1 汽油机     22 – 27  m/s  ← **工程界公认的活塞速度上限**
""")
mps_20000 = mps(20000)
mps_f1 = mps(20000, 0.0397)   # F1 冲程 39.7 mm
print(f"  复算：20000 rpm @ 冲程 135 mm ⇒ MPS = {mps_20000:.1f} m/s")
print(f"        F1 20000 rpm @ 冲程 39.7 mm ⇒ MPS = {mps_f1:.1f} m/s")
ok(f"⇒ 柴油机 20000 rpm 的 MPS = **{mps_20000:.1f} m/s**，是 F1 极限的 **{mps_20000/mps_f1:.1f} 倍**")
warn(f"⇒ 比车用柴油机红线（约 13 m/s）高 **{mps_20000/13:.1f} 倍**")

# ============================================================
sec("Q2  往复惯性力 —— 活塞/连杆要承受多少吨？")
# ============================================================
print("""
  活塞在上止点(TDC)的**最大往复加速度**（含连杆有限长度修正）：
        a_max = r·ω²·(1 + r/L)          r = 冲程/2,  ω = 2πn
  惯性力：F = m · a_max
""")
r = STROKE / 2
lam = r / ROD

def a_max(rpm):
    w = 2 * math.pi * rpm / 60.0
    return r * w**2 * (1 + lam)

def F_inert(rpm, m=PISTON_M):
    return m * a_max(rpm)

print(f"  r = {r*1000:.1f} mm,  L/r = {1/lam:.2f}  ⇒ (1 + r/L) = {1+lam:.3f}")
print()
print(f"  {'转速':>8} | {'最大加速度':>14} | {'= 重力倍数':>12} | {'惯性力':>12} | {'≈ 吨力':>10}")
print("  " + "-" * 78)
for rpm in [60, 800, 1150, 4000, 6000, 12000, 20000]:
    a = a_max(rpm)
    g = a / 9.81
    F = F_inert(rpm)
    star = " ★" if rpm in (4000, 20000) else ""
    print(f"  {rpm:>8} | {a/1000:>10.1f} km/s² | {g:>10.0f} g | {F/1000:>9.1f} kN | {F/9806.65:>8.1f} t{star}")
print("  " + "-" * 78)

F4k = F_inert(4000)
F20k = F_inert(20000)
ok(f"20000 rpm 时惯性力 = **{F20k/1000:.0f} kN ≈ {F20k/9806.65:.0f} 吨力**（单缸、每个上止点一次）")
ok(f"4000 rpm 时 = {F4k/1000:.1f} kN ≈ {F4k/9806.65:.1f} 吨力")
ok(f"⇒ 比值 = (20000/4000)² = **{F20k/F4k:.0f} 倍**（惯性力 ∝ 转速²，这是纯几何结论）")

print("""
  ★ 材料能不能撑住？（两个关键件）

    ① 活塞（铝硅合金，工作时 250–350 °C）
       室温抗拉 ~250 MPa ⇒ **高温下仅 ~80–120 MPa**
       活塞销座有效承力截面（保守取 1500 mm²）
        ⇒ 允许力 ≈ 120e6 × 1500e-6 = 180 kN
    ② 连杆（锻钢，疲劳极限 ~300 MPa；小头/螺栓截面 ~500 mm²）
        ⇒ 允许力 ≈ 150 kN
""")
F_allow = 180e3
print(f"  复算：需要 {F20k/1000:.0f} kN ／ 允许约 {F_allow/1000:.0f} kN"
      f" ⇒ **超限 {F20k/F_allow:.1f} 倍**")
# 反解：活塞能承受的最高转速
n_limit = math.sqrt(F_allow / (PISTON_M * r * (1 + lam))) * 60 / (2 * math.pi)
ok(f"⇒ 由材料反解：这台机器的活塞**理论上限 ≈ {n_limit:.0f} r/min**（已是理想化算法）")
print(f"     ★ 注意 {n_limit:.0f} r/min 已**远高于**柴油机实际红线（约 4000）——")
print(f"       说明真实限制还叠加了**燃烧、热负荷、润滑**等因素，实际更低。")

# ============================================================
sec("Q3  对比 F1 —— 为什么 F1 能到 20000 rpm 而柴油机不能")
# ============================================================
print("""
  F1（2010 年代 V8 时代）确实能到 18000–20000 rpm。**但它是靠「重新设计整个机器」做到的**：
""")
F1 = {"冲程": 0.0397, "r": 0.01985, "连杆": 0.100, "活塞质量": 0.25, "MPS": mps(20000, 0.0397)}
F1_lam = F1["r"] / F1["连杆"]
F1_a = F1["r"] * (2*math.pi*20000/60)**2 * (1 + F1_lam)
F1_F = F1["活塞质量"] * F1_a
print(f"  {'项':>12} | {'F1 (20000 rpm)':>18} | {'柴油机 (20000 rpm)':>20} | {'倍数':>8}")
print("  " + "-" * 72)
rows = [
    ("冲程", f"{F1['冲程']*1000:.1f} mm", f"{STROKE*1000:.0f} mm", f"{STROKE/F1['冲程']:.1f}×"),
    ("活塞质量", f"{F1['活塞质量']*1000:.0f} g", f"{PISTON_M*1000:.0f} g", f"{PISTON_M/F1['活塞质量']:.1f}×"),
    ("MPS", f"{mps(20000,0.0397):.1f} m/s", f"{mps(20000):.1f} m/s", f"{mps(20000)/mps(20000,0.0397):.1f}×"),
    ("最大加速度", f"{F1_a/1000:.0f} km/s²", f"{a_max(20000)/1000:.0f} km/s²", f"{a_max(20000)/F1_a:.1f}×"),
    ("惯性力", f"{F1_F/9806.65:.1f} t", f"{F20k/9806.65:.0f} t", f"{F20k/F1_F:.1f}×"),
]
for name, a, b, c in rows:
    print(f"  {name:>12} | {a:>18} | {b:>20} | {c:>8}")
print("  " + "-" * 72)
ok("⇒ 柴油机要承受的惯性力是 F1 的 **约 %.0f 倍**" % (F20k/F1_F))
print("""
  ★ F1 为此付出的代价：
     · 钛合金连杆、镁/铝超轻活塞、干式油底壳、气动气门（20,000 rpm 弹簧来不及）
     · 单台发动机成本 **数十万至百万美元级**，寿命仅几小时
     · **而且 F1 是汽油预混燃烧，火焰传播快；柴油是扩散燃烧，天生更慢**
""")
warn("⇒ 「把柴油机强化一下就能到 20000 rpm」不成立 —— 需要的是**换一整套机器**，不是强化")

# ============================================================
sec("Q4  ★「死飞」：飞轮爆裂转速（flywheel burst）")
# ============================================================
print("""
  ★ 老师用的词是「**死飞限制**」。在旋转机械工程里，最贴切的对应是
     **飞轮爆裂转速**（flywheel burst speed）—— 超过它飞轮因离心力自行解体。

  轮缘环向应力（薄环近似）：  σ = ρ · v²        v = ω·R （轮缘线速度）
  ⇒ 材料极限决定 v_max，进而决定 n_max。
""")
MATS = [
    ("铸铁（常见飞轮）", 7200, 50, "工程安全限（铸件缺陷）"),
    ("球墨铸铁", 7100, 80, "工程安全限"),
    ("锻钢", 7850, 150, "工程安全限"),
    ("★ 碳纤维复材", 1600, 900, "赛车级，成本极高"),
]
print(f"  {'材料':>18} | {'密度':>10} | {'安全线速度':>12} | 备注")
print("  " + "-" * 74)
for name, rho, v, note in MATS:
    print(f"  {name:>18} | {rho:>7} kg/m³ | {v:>9.0f} m/s | {note}")
print("  " + "-" * 74)

print(f"""
  本机飞轮：R = {FLYWHEEL_R*1000:.0f} mm（直径 {FLYWHEEL_R*2000:.0f} mm）
""")
print(f"  {'转速':>8} | {'轮缘线速度':>12} | 对比")
print("  " + "-" * 74)
for rpm in [800, 2000, 4000, 6000, 8000, 12000, 20000]:
    w = 2 * math.pi * rpm / 60.0
    v = w * FLYWHEEL_R
    if v < 50: judge = "✅ 铸铁飞轮安全"
    elif v < 80: judge = "🟡 铸铁临界（须球墨铸铁）"
    elif v < 150: judge = "⚠️ 须锻钢"
    elif v < 300: judge = "🔴 锻钢超限 ⇒ 须碳纤维复材"
    elif v < 900: judge = f"🔴🔴 碳纤维复材（用到 {v/900*100:.0f}% 极限）"
    else: judge = "❌❌ 无任何常规材料"
    print(f"  {rpm:>8} | {v:>9.0f} m/s | {judge}")
print("  " + "-" * 74)
v20k = 2 * math.pi * 20000 / 60.0 * FLYWHEEL_R
ok(f"20000 rpm 时飞轮轮缘线速度 = **{v20k:.0f} m/s**（≈ {v20k/343:.1f} 倍音速）")
warn(f"⇒ 是铸铁安全线（50 m/s）的 **{v20k/50:.1f} 倍**、锻钢（150 m/s）的 **{v20k/150:.1f} 倍**")
warn(f"⇒ 即使用赛车级碳纤维（900 m/s），也已用到 **{v20k/900*100:.0f}%** 的极限")
warn("⇒ ★ 这就是「死飞」的物理含义：**飞轮会先于活塞解体**")
warn("⇒ 而★ **飞轮比活塞更难换** —— 活塞可以轻量化，飞轮的转动惯量是柴油机运转**必需**的")
print("""
  ★ 补充：飞轮为什么不能轻量化到赛车水平？
     · 柴油机压缩比高（18:1）⇒ 每循环压缩功大 ⇒ 需要飞轮储能来**越过压缩上止点**
     · 多缸机（8 缸）虽然叠加更平顺，但飞轮惯量仍需匹配
     · **飞轮惯量是柴油机的功能需求，不是设计冗余** ⇒ 不能为了转速而随意减小
""")

# 飞轮储能
print()
E20k = 0.5 * (0.5 * FLYWHEEL_M * FLYWHEEL_R**2) * (2*math.pi*20000/60)**2
E4k = 0.5 * (0.5 * FLYWHEEL_M * FLYWHEEL_R**2) * (2*math.pi*4000/60)**2
print(f"  储能复算：E = ½Iω²,  I = ½mR² = {0.5*FLYWHEEL_M*FLYWHEEL_R**2:.3f} kg·m²")
print(f"    4000 rpm  ⇒ E = {E4k/1000:.1f} kJ")
print(f"    20000 rpm ⇒ E = {E20k/1000:.0f} kJ  (={E20k/1e6:.2f} MJ)， 是 4000 rpm 的 **{E20k/E4k:.0f} 倍**")
warn("⇒ 若飞轮在 20000 rpm 解体，释放能量相当于把 1 吨物体举高 %.0f 米" % (E20k/9806.65))

# ============================================================
sec("Q5  燃烧时间常数 —— 柴油扩散燃烧在 20000 rpm 下来得及吗？")
# ============================================================
print("""
  柴油机是**扩散燃烧**：喷油 → 雾化 → 混合 → 着火延迟 → 扩散火焰。
  各阶段都需要**物理时间**，不随转速缩短。
""")
print(f"  {'转速':>8} | {'一转':>10} | {'60° CA':>10} | {'180° CA':>10} | 判定")
print("  " + "-" * 74)
for rpm in [800, 1150, 2000, 4000, 6000, 12000, 20000]:
    t_rev = 60000.0 / rpm
    t60 = t_rev * 60 / 360
    t180 = t_rev * 180 / 360
    if t60 > 3.0: judge = "✅ 各阶段充裕"
    elif t60 > 1.5: judge = "🟡 勉强"
    elif t60 > 0.8: judge = "⚠️ 临界（赛车柴油机水平）"
    else: judge = "❌ 来不及"
    print(f"  {rpm:>8} | {t_rev:>7.2f} ms | {t60:>7.2f} ms | {t180:>7.2f} ms | {judge}")
print("  " + "-" * 74)
ok("柴油典型需求：着火延迟 **0.5 – 1.0 ms** ＋ 扩散燃烧 **1 – 2 ms** ⇒ 合计 **1.5 – 3.0 ms**")
warn(f"20000 rpm 时「燃烧窗口」只有 {60/360*60000/20000:.2f} ms ⇒ **差 {1.5/0.5:.0f} – {3.0/0.5:.0f} 倍**")
warn("⇒ ★ 即便机械能撑住，**柴油也烧不完** ⇒ 这解释了柴油机红线为什么只有 4000–5000 rpm")

# ============================================================
sec("Q6  60 rpm 怠速 —— 压缩热损失与漏气")
# ============================================================
print("""
  老师说的「最低怠速 60 rpm」= 1 转/秒。四冲程下：
    一个完整循环 = 2 转 = **2 秒**；压缩行程（180° CA）= **1 秒**
""")
print(f"  {'转速':>8} | {'压缩行程耗时':>14} | {'相对 800 rpm':>14} | 说明")
print("  " + "-" * 74)
for rpm in [60, 200, 400, 800, 1150]:
    t = (180.0 / 360.0) * (60.0 / rpm)
    print(f"  {rpm:>8} | {t*1000:>11.0f} ms | {t/((180/360)*60/800):>12.1f}× | "
          + ("★ 老师说的 60 rpm：压缩要 0.5 秒" if rpm == 60 else ""))
print("  " + "-" * 74)

ok("压缩行程时间随转速**反比拉长**：60 rpm 时是 800 rpm 的 **13.3 倍**")
print("""
  ★ 两个后果：
    ① **漏气**：活塞环不是绝对密封。压缩时间越长，漏气越多 ⇒ 压缩终了压力/温度越低
    ② **散热**：缸壁是冷的（相对），压缩时间越长，气体把热量传给缸壁越多

  ⇒ 活塞环漏气量近似 ∝ 时间 ⇒ 漏气量 ↑13 倍
  ⇒ 压缩终了温度显著下降 ⇒ **可能压不着柴油**（自燃点 257 °C，但需要压缩终温 500 °C+ 才有把握）
""")
warn("⇒ 主流柴油机的怠速下限一般 **550 – 750 rpm**；60 rpm 远低于此")
print("""
  ★ 但也有**对老师有利**的说法（如实列出）：
     · **单缸大飞轮**的老式柴油机（如农用单缸机）最低可到 **200 – 400 rpm**
     · 若气缸尺寸很小、漏气面积/容积比低，低速维持性会好一些
     · 「60 rpm」若指**冷机拖转**（起动机带动，不燃烧），则完全可能
""")

# ============================================================
sec("Q7  ★ 声音频率 —— 各转速下的点火频率（最便宜的可检验判据）")
# ============================================================
print("""
  ★★ 这是一条**零成本、可当场验证**的判据。

  四冲程、四缸：每转有 2 次点火 ⇒ 点火基频  f = (N/60) × (缸数/2)
""")
print(f"  {'转速':>8} | {'四缸点火频率':>14} | {'六缸':>10} | {'八缸':>10} | 人耳感知")
print("  " + "-" * 86)
for rpm in [60, 200, 400, 800, 1150, 2000, 4000, 8000, 20000]:
    f4 = rpm / 60 * 2
    f6 = rpm / 60 * 3
    f8 = rpm / 60 * 4
    if f4 < 20: p = "❌ 听不到（次声），只能**感到振动**"
    elif f4 < 60: p = "低频「突…突…」"
    elif f4 < 200: p = "清晰「隆隆」低音"
