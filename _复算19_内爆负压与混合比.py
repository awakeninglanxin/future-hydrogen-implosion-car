"""
【复算 19】内爆变负压：HHO / 空气混合比的定量关系 + 能量账
================================================================
问题（老师 2026-09-12）：
  Q1 布朗气与空气以什么比例混合 → 先外爆、后内爆变负压？
  Q2 什么比例 → 直接内爆变负压（不先外爆）？
  Q3 内爆变负压需要怎样的氢氧 / 空气混合？
  Q4 极微量单质氢混入布朗气？
  Q5 有没有人单独用纯单质氢内爆做实验？
  Q6 「变体1（9+/9−）单质氢游离水中，难与自身成氢键」是否 Joe Cell 动力源？

本脚本只做「可独立复算」的部分：Q1/Q2/Q3 的定量骨架 + 能量账。
Q4/Q5/Q6 属文献检索结论，见网页正文，不在此脚本内伪造数字。
"""
import math

R = 8.314462618      # J/(mol·K)
P_ATM = 101.325      # kPa
T25 = 298.15
P_SAT_25 = 3.169     # kPa，水在 25 °C 的饱和蒸气压（IAPWS 常用值 3.169 kPa）
P_SAT_100 = 101.325  # kPa

def hr(t): print("\n" + "=" * 76 + "\n" + t + "\n" + "=" * 76)

# ---------------------------------------------------------------- Q1/Q3
hr("Q1/Q3：核心公式 —— 冷凝后的压力只取决于「空气占多少」")
print("""
密闭容器，恒容，点燃后冷却到 25 °C。设初始：
    HHO(2H2+O2) = a mol        空气 = b mol(0.21 O2 + 0.79 N2)
完全反应（H2 必为限制性，因为空气还额外带 O2）：
    耗 O2 = a/3     剩 O2 = 0.21b     剩 H2 = 0     剩 N2 = 0.79b
    ⇒ 不凝气体总量 = 0.21b + 0.79b = b      ← ★ 恰好等于「空气的摩尔数」
    ⇒ 冷凝后绝压 P ≈ [b/(a+b)] × 101.325 kPa + 3.169 kPa
                  = (空气摩尔分数) × 101.325 + 3.169

★ 一句话：空气唯一的作用，就是往容器里塞「永不冷凝的 N2」。
   每多 1% 空气，负压就浅 1%×101.325 ≈ 1 kPa。
""")

print("%-10s %-12s %-14s %-14s %-12s" % ("空气分数", "HHO分数", "P绝压kPa", "表压kPa", "表压atm"))
print("-" * 76)
for air in [0.0, 0.10, 0.20, 0.30, 0.40, 0.50, 0.60, 0.70, 0.80, 0.90, 1.00]:
    p_abs = air * P_ATM + P_SAT_25
    p_g = p_abs - P_ATM
    print("%-10.0f%% %-12.0f%% %-14.2f %-14.1f %-12.3f" % (air*100, (1-air)*100, p_abs, p_g, p_g/P_ATM))

print("""
⇒ 三条硬结论：
 ① 负压最深 = 纯 HHO（空气 0%）⇒ 表压 -98.2 kPa = -0.969 atm
    ★ 不论怎么配，都不可能比 -1 atm 更负（这是容器的物理上限）
 ② 空气越多，负压越浅，且线性
 ③ 想要深负压 ⇒ 必须「纯 HHO，不掺空气」——与「掺氢入柴油机进气」正相反
""")

# ---------------------------------------------------------------- 外爆不可避免
hr("Q2：『先外爆』是不可避免的 —— 用摩尔数 + 温度算给你看")
print("""
纯 HHO 2H2+O2 → 2H2O，恒容点燃瞬间：
    摩尔数：3 mol → 2 mol（降到 2/3）
    温度：  298 K → 绝热火焰温度
    压力比 P/P0 = (n1/n0) × (T1/T0)

    H2/O2 绝热火焰温度 ≈ 3080 K   ⇒ P/P0 = (2/3)×(3080/298) = %.1f 倍
    ⇒ 这就是「先外爆」：压力先冲到约 %.0f 个大气压
""" % ((2/3)*(3080/298), (2/3)*(3080/298)*P_ATM/P_ATM))
p_ratio = (2/3)*(3080/298)
print("    复算：P/P0 = %.2f  ⇒ 峰值约 %.1f bar(绝压)" % (p_ratio, p_ratio*1.01325))

print("""
⇒ 【关键】任何 HHO 点火都「先外爆」——这是放热 + 升温的必然。
   「直接内爆」在物理上不存在；圈内说的「不爆不燃、平顺内爆」，
   指的是「**没有爆轰声**」，即燃烧速度慢、不形成激波，而不是「没有先升压」。

   要让燃烧变慢（趋近「无声内爆」），主流已知手段：
     ① 富燃 / 贫燃（偏离化学计量）        → 燃烧速度下降
     ② 稀释（掺 N2 / 水蒸气 / 排气再循环）→ 燃烧速度下降
     ③ 低压、大长径比、加障碍物抑制湍流   → 抑制爆燃转爆轰(DDT)
   ★★ 但 ①②③ 全都「把不凝气塞进容器」⇒ **负压同时变浅**
   ⇒ 这就是本课题的真正张力（trade-off）：
       「内爆要平稳」与「负压要深」是**互相冲突**的两个要求。
""")

# ---------------------------------------------------------------- 时间尺度
hr("★ Q3 的致命细节：冷凝需要「秒」，发动机冲程只有「毫秒」")
print("""
能量不是「有负压」就算数，还要看**来得及来不及**。

  实测数据（Oxyhydrogen Pulse Detonation Combustion Pump 专利实测）：
    40 L 燃烧室 + 22 L 水 + 18 L 空气，22 °C，14.4 psia
    装药 1.3 g HHO：峰值 17.2 psia（0.29 s），回落到 **5.00 psia**
                    达到「极限低压的 50%」用了 **3.45 s**
    装药 2.2 g HHO：峰值 45.3 psia（0.095 s），回落到 **4.38 psia**
                    达到 50% 极限低压用 **2.65 s**
  ⇒ 负压的建立是 **秒级**（2.6 – 3.5 s 才走一半）
  ⇒ 而发动机一个冲程 ≈ 10 ms（3000 rpm）= **秒的百分之一**

  ⇒ ★ 结论：**在气缸里，水蒸气根本来不及冷凝**
    负压来不及形成，活塞已经到下一个循环了。
    这解释了为什么 Joe Cell / HHO 内爆发动机
    「在泵上做得到（秒级循环）、在发动机上做不到（毫秒级循环）」。

  ⇒ 唯一的例外是**直接喷水**（雾化水吸热+快速蒸发/冷凝），
    这正是水喷射/水雾抑爆与某些内爆泵专利的做法。
""")

# ---------------------------------------------------------------- 能量账
hr("能量账：大气压推活塞，最多能拿回多少？")
V_L = 1.0                       # 排量 1 L
V_m3 = V_L / 1000.0
W_atm = P_ATM * 1000 * V_m3     # Pa × m³ = J，全冲程满压差
print("① 负压做功上界（1 L 排量、全冲程维持 -1 atm 压差）：")
print("    W = ΔP × V = %.0f Pa × %.6f m³ = **%.1f J**" % (P_ATM*1000, V_m3, W_atm))

# HHO 的化学能
mol_per_L_25C = 1.0 / 24.466   # 25°C、1 atm 理想气体摩尔体积 24.466 L/mol
n_hho = mol_per_L_25C
n_h2 = n_hho * 2/3
Q_hho_kJ = n_h2 * 241.826      # kJ/mol，按生成水蒸气（LHV）
print("\n② 1 L 常温常压 HHO 的化学能（LHV，生成水蒸气）：")
print("    n(HHO) = 1/24.466 = %.5f mol   n(H2) = %.5f mol" % (n_hho, n_h2))
print("    Q = %.5f mol × 241.826 kJ/mol = **%.3f kJ**" % (n_h2, Q_hho_kJ))
print("\n③ 对比：")
print("    大气压做功  = %.4f kJ" % (W_atm/1000))
print("    化学能      = %.3f kJ" % Q_hho_kJ)
print("    ⇒ 大气压只占化学能的 **%.2f%%**" % (W_atm/1000 / Q_hho_kJ * 100))

print("""
⇒ 两条都必须讲清：
   ✅ 大气压**确实**在推活塞（这一句没错，Otto-Langen 1867 就是这么干的）
   ❌ 但它是**化学能的一个小尾巴（~1.5%）**，不是「额外的免费能源」
   ⇒ 而且实测时间尺度（秒）比发动机冲程（毫秒）慢两个量级 ⇒ 连这 1.5% 也拿不到
""")

# ---------------------------------------------------------------- Otto-Langen 历史锚
hr("历史锚点：Otto-Langen 大气压发动机（1867）—— 真的用过这个原理")
print("""
  · 原理：先让气缸里的燃气膨胀、再冷却成真空，然后**大气压把活塞推回去**做功
  · 效率：**11–14%**（同期 Lenoir 无压缩发动机 4–5%）
  · 产量：约 5,000 台；1882 年停产（被 Otto 四冲程取代）
  · 关键差异：它烧的是**煤气/空气**（产物 CO2 + H2O 都会冷凝/溶解）
    ⇒ 负压更容易形成；而 H2/空气燃烧后**剩大量 N2 不凝**，负压天生更浅
  ⇒ 这是「负压做功可行、但天花板很低」的**最硬的历史证据**。
""")

# ---------------------------------------------------------------- 原子氢
hr("Q5：原子氢（单质氢）内爆 —— 主流实测数据")
print("""
  2H· → H2    摩尔数 2 → 1，体积**减半** ⇒ 必然产生负压
  · 复合焓（ATcT v1.220 权威数据）：
        0 K  : **432.068 kJ/mol**
      298 K  : **435.996 kJ/mol**
    ★ 与 H2 的解离能是**同一个数值** —— 先存后取，不是新能量
  · 原子氢寿命：
      气相：毫秒级（Langmuir 1912 起）
      水中溶解态 H(aq)：**半衰期约 5 分钟**（1966 Electrochim. Acta 实测）
      水中溶解度极低，且 H(aq) 呈**疏水性**（住在 0.5 nm 笼形空腔里）
  · 有无人做过「纯单质氢内爆」实车？
      → **没有**。原子氢只作为「表面复合热源」存在（Langmuir 原子氢焊，3500–4000 °C）
        从未有人做成动力循环，因为它需要**持续的电弧/热丝输入**才能维持。
""")

# ---------------------------------------------------------------- Q6
hr("Q6：老师提的「变体1（9+/9−）游离水中、不成氢键」—— 主流有什么对应物？")
print("""
  圈内说法：变体1 的 Anu 是 9 正 / 9 负（电中性），游离在水中难以与自身结合成氢键，
            因而可能是 Joe Cell 的动力源泉。

  逐层核对：
  ① 名词层：「氢键」在主流里是**分子间**作用（H2O···H2O），
     单个 H 原子之间**不存在氢键** ⇒ 「不成氢键」这个说法本身要改写。
  ② 对象层：但老师的**物理直觉**有真实对应物 ——
     水中溶解的原子氢 H(aq) 确实是**疏水溶质**（2014 论文原话：
     "a hydrophobic solute akin to molecular hydrogen"），
     它**不参与水的氢键网络**，而是待在约 0.5 nm 的笼形空腔里，
     且**寿命长达 5 分钟**（比气相毫秒级长 5 个量级）。
  ③ 机制层：若电解持续产生 H(aq)，且它能在水中存活数分钟，
     则有可能被气流带出、在气缸/水面复合 ⇒ 释放 432 kJ/mol（真实能量）。
     ★ 但**源头仍是电解电** ⇒ 判据③「看它没算什么」：
       Joe Cell 声称「断开电池后仍持续 breeding」= 持续产原子氢
       ⇒ 这需要一个**持续的能量输入**，否则等于凭空产生
  ④ 结论：**方向可查、结论未定**。
     「H(aq) 疏水 + 长寿命」是主流真实存在的现象，
     但把它接到「Joe Cell 自持供能」这一步，**至今没有第三方复现**。
""")

