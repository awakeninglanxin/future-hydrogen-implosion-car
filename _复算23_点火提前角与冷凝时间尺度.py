import math

# =====================================================================
# 输入与常数
# =====================================================================
RPM_LIST = [500, 800, 1150, 1500, 2000, 3000, 6000]
ADV_DEG = 8.0            # ★ 老师给的提前角
ADV_MAX = 80.0           # 库内圈内材料（Rover 改装）出现过的最大提前角，作敏感性上界

# ★ 负压建立的时间锚点（实测半程，见 12 号文档 §四）：
#   Oxyhydrogen Pulse & Rotary Detonation Combustion Pump 专利实测
#     · 1.3 g HHO：峰值 17.2 psia → 极限 5.00 psia，达半程 3.45 s
#     · 2.2 g HHO：峰值 45.3 psia → 极限 4.38 psia，达半程 2.65 s
T_COND_LO, T_COND_HI = 2.65, 3.45        # s

V_PUMP_L = 40.0      # L，泵体试验燃烧室容积
V_CYL_L = 0.4        # L，单缸排量（按 JCB 448 的 4.8 L / 4 缸）

GAMMA = 1.40
T_PEAK = 2400.0      # K，稀燃氢峰值温度量级下界
T_COND_WATER = 373.15  # K，1 atm 下水蒸气冷凝温度

POWER_STROKE_DEG = 180.0   # 上止点 → 下止点
EVO_DEG = 180.0            # 排气门大致在下止点开

rec = []
def r(tag, val, ok=True):
    rec.append((tag, val, "OK" if ok else "!!"))
    print("  [%s] %s = %s" % ("OK" if ok else "!!", tag, val))

def sec(t):
    print("\n" + "=" * 74)
    print(t)
    print("=" * 74)

def ms_per_deg(rpm):
    """每度曲轴的时间（ms）"""
    return 60.0 / rpm / 360.0 * 1000.0

def rev_ms(rpm):
    """一转（360°）的时间（ms）"""
    return 60.0 / rpm * 1000.0


# =====================================================================
sec("Q1  ★ 提前 8° 买到多少时间？（正面回答老师的问题）")
# =====================================================================
print("  每度曲轴时间 = 60/rpm/360\n")
print("  转速      每度曲轴     8° 买到      一转时间   8°占一转   8°占动力冲程(180°)")
for rpm in RPM_LIST:
    d, rv = ms_per_deg(rpm), rev_ms(rpm)
    print("  %5d    %8.4f ms  %8.3f ms  %8.2f ms   %5.1f%%      %5.1f%%"
          % (rpm, d, d * ADV_DEG, rv, ADV_DEG / 360 * 100,
             ADV_DEG / POWER_STROKE_DEG * 100))

r("1150 r/min 时 8° 买到的时间", "%.2f ms" % (ms_per_deg(1150) * ADV_DEG))
r("3000 r/min 时 8° 买到的时间", "%.2f ms" % (ms_per_deg(3000) * ADV_DEG))
r("最有利情况（最低转速 500 r/min）8° 买到", "%.2f ms" % (ms_per_deg(500) * ADV_DEG))
print("\n  ⇒ 提前 8° 买到的是**毫秒**量级（0.2 – 2.7 ms），且**与转速成反比**。")


# =====================================================================
sec("Q2  ★★ 与「冷凝所需时间」对比 —— 决定性的比值")
# =====================================================================
print("  负压建立半程时间（实测）：%.2f – %.2f s = %.0f – %.0f ms"
      % (T_COND_LO, T_COND_HI, T_COND_LO * 1000, T_COND_HI * 1000))
print("\n  转速   提前角    买到的      需要/买到（倍）")
for rpm, adv in ((1150, 8), (3000, 8), (1150, 80), (3000, 80)):
    buy = ms_per_deg(rpm) * adv
    print("  %5d   %4.1f°   %7.2f ms   %6.0f – %6.0f 倍"
          % (rpm, adv, buy, T_COND_LO * 1000 / buy, T_COND_HI * 1000 / buy))

r("8° @1150 r/min 的差距", "%.0f – %.0f 倍"
  % (T_COND_LO * 1000 / (ms_per_deg(1150) * 8), T_COND_HI * 1000 / (ms_per_deg(1150) * 8)))
print("\n  ⇒ 差 **约 3 个数量级（10^3）**。")
print("  ⇒ 即便按圈内材料里出现过的 **80°** 算，也只买到 %.1f ms（@1150 r/min），"
      % (ms_per_deg(1150) * 80))
print("     仍差 %.0f – %.0f 倍。" % (T_COND_LO * 1000 / (ms_per_deg(1150) * 80),
                                      T_COND_HI * 1000 / (ms_per_deg(1150) * 80)))


# =====================================================================
sec("Q3  ★★ 最有利的算法：把「整个动力冲程」全给它，够不够？")
# =====================================================================
print("  有人会说：不该只算 8°，整个动力冲程（180° CA）都是可用时间。")
print("  那就把**整段**都给它 —— 8° 只是其中的 %.1f%%。\n" % (8 / 180 * 100))
print("  转速    整个动力冲程(180°)     需要/全给（倍）")
for rpm in (500, 800, 1150, 2000, 3000):
    win = ms_per_deg(rpm) * POWER_STROKE_DEG
    print("  %5d    %10.1f ms        %6.0f – %6.0f 倍"
          % (rpm, win, T_COND_LO * 1000 / win, T_COND_HI * 1000 / win))
r("整个动力冲程 @1150 r/min", "%.1f ms ⇒ 仍差 %.0f – %.0f 倍"
  % (ms_per_deg(1150) * 180, T_COND_LO * 1000 / (ms_per_deg(1150) * 180),
     T_COND_HI * 1000 / (ms_per_deg(1150) * 180)))
print("\n  ⇒ ★ 即便把**整个动力冲程**都用来等冷凝，在 1150 r/min 下仍有 **约 100 倍**缺口。")
print("     8° 是这 100 倍缺口里的一个零头。")

print("\n  ★ 换一种更直观的说法：「用转数算」")
for rpm in (1150, 3000):
    revs_lo = T_COND_LO / (60.0 / rpm)
    revs_hi = T_COND_HI / (60.0 / rpm)
    print("     @%5d r/min，冷凝半程需要 **%.0f – %.0f 转**"
          % (rpm, revs_lo, revs_hi))
r("冷凝半程 ≈ 多少转 @1150 r/min", "%.0f – %.0f 转"
  % (T_COND_LO / (60.0 / 1150), T_COND_HI / (60.0 / 1150)))
print("     ⇒ 发动机要**空转 50 圈以上**，才能得到泵体一圈就有的冷凝程度。")


# =====================================================================
sec("Q4  ★ 对老师最有利的算法：腔体尺度缩放（必须如实算）")
# =====================================================================
# 那个「秒级」是在 40 L 大腔体 + 22 L 水 的试验台上测的。
# 发动机缸内腔体小得多 ⇒ 表面积/体积比大得多 ⇒ 散热应更快。
# 若按热扩散标度 τ ∝ L²（L = V^(1/3)）：
L_pump = V_PUMP_L ** (1.0 / 3.0)
L_cyl = V_CYL_L ** (1.0 / 3.0)
scale = (L_cyl / L_pump) ** 2
print("  泵体 V = %.0f L ⇒ 线性尺度 %.3f ;  缸内 V = %.1f L ⇒ %.3f"
      % (V_PUMP_L, L_pump, V_CYL_L, L_cyl))
r("τ ∝ L² 缩放因子", "%.4f（约 1/%.1f）" % (scale, 1 / scale))
t_lo_s, t_hi_s = T_COND_LO * 1000 * scale, T_COND_HI * 1000 * scale
r("缩放后缸内冷凝半程时间", "%.0f – %.0f ms" % (t_lo_s, t_hi_s))

print("\n  缩放后 vs 整个动力冲程：")
for rpm in (500, 800, 1150, 2000):
    win = ms_per_deg(rpm) * POWER_STROKE_DEG
    print("     %5d r/min：动力冲程 %6.1f ms  vs 缩放后冷凝 %6.0f ms  ⇒ %s"
          % (rpm, win, t_lo_s, "来得及 ✅" if t_lo_s <= win else "仍不够 ❌"))
rpm_need = 60.0 / (t_lo_s / 1000.0 / 2.0)   # 180° = 半个循环 = 30/rpm 秒
r("按 L² 缩放，动力冲程能容下冷凝需转速 ≤", "约 %.0f r/min" % rpm_need)
print("\n  ⇒ ★ 这个缩放把缺口从 **10^3 缩到 ~10^1** —— **必须如实写出来**，")
print("     它确实大幅削弱了「绝无可能」的说法。**但两点不变**：")
print("     ① 即使按最宽松的缩放，8° 买到的 1.16 ms 仍只占所需时间的 **不足 1%**；")
print("     ② 真正的杠杆是**转速与腔体尺度**（还有直接喷水），**不是提前角**。")

# 补充：这个缩放对发动机其实偏乐观的一点
print("\n  ⚠️ 而且这个缩放对发动机是**偏乐观**的，两点反证：")
print("     · 泵体壁面/水接近 22 °C（冷壁，利于冷凝）；缸壁约 200 °C（热壁，不利于冷凝）")
print("     · 泵体有 22 L 水的巨大热容可吸热；缸内没有这样的热沉")


# =====================================================================
sec("Q5  另一条路：靠活塞「膨胀冷却」让水蒸气自己冷凝？")
# =====================================================================
r_need = (T_PEAK / T_COND_WATER) ** (1.0 / (GAMMA - 1.0))
print("  绝热膨胀 T2 = T1 / r^(γ-1)，γ = %.2f，T1 = %.0f K" % (GAMMA, T_PEAK))
r("所需膨胀比（降到 100 °C）", "≈ %.0f : 1" % r_need)
print("\n  实际发动机可用膨胀比（≈ 压缩比）：")
for cr in (14, 18, 20):
    t2 = T_PEAK / (cr ** (GAMMA - 1.0))
    print("     CR %2d ⇒ 膨胀终了 %.0f K = %.0f °C（远高于 100 °C）"
          % (cr, t2, t2 - 273.15))
r("可用 vs 需要", "14–20 vs %.0f ⇒ 差 %.0f 倍" % (r_need, r_need / 20))
print("\n  ⇒ 靠活塞膨胀冷却到冷凝，**物理上做不到**。")


# =====================================================================
sec("Q6  一个必须先解决的矛盾：H₂ 在柴油 CR 下会「自己先着火」")
# =====================================================================
print("  ★ 方向性问题：老师说的是「提前」。但氢在柴油机压缩比下：")
for cr in (14, 18, 20, 21.2):
    tc = 298.15 * (cr ** (GAMMA - 1.0)) - 273.15
    print("     CR %4.1f ⇒ 压缩终了 %.0f °C   %s"
          % (cr, tc, "＞氢自燃点 585 °C ⇒ 压着就着" if tc > 585 else "＜585 °C ⇒ 不会自燃"))
r("氢自燃点", "585 °C（柴油 257 °C）")
print("\n  ⇒ 在 CR ≥ 14 的柴油机上，HHO/氢**在压缩途中就会自燃**（预点火），")
print("     其「着火时刻」比任何火花塞设定都**更早**。")
print("     ⇒ 想用火花塞控时，必须**先把压缩比降下来**（主流做法），")
print("       而不是在原柴油机上「往前调 8°」。")


# =====================================================================
sec("Q7  历史答案：Otto-Langen（1867）怎么解决这个时间问题的")
# =====================================================================
print("  它的办法**不是**「把点火提前几度」，而是两条：")
print("    ① **把机器放到极慢**：早期 0.5 hp @ **80 r/min** ⇒ 一转 %.0f ms" % (60.0 / 80 * 1000))
print("    ② **让活塞在上止点「等」**：爆炸把活塞顶起后机构扣住，")
print("       等缸内冷却收缩成真空，再放开让大气压推它做功。")
r("Otto-Langen 转速", "80 r/min（一转 %.0f ms，比 1150 r/min 慢 %.0f 倍）"
  % (60.0 / 80 * 1000, (60.0 / 80 * 1000) / rev_ms(1150)))
print("\n  ⇒ ★ 它是**用机械结构把「时间」硬等出来**的，不是调点火相位调出来的。")
print("     （它的产物是 CO₂+H₂O，CO₂ 可溶、H₂O 冷凝 ⇒ 负压天生易形成；"
      "而 H₂/空气助燃剩大量 N₂ 不凝。）")


# =====================================================================
sec("Q8  ★ 相位账：提前角有没有物理上限？（为什么不能「一路往前调」）")
# =====================================================================
# 点火提前角越大，燃烧越多发生在压缩冲程 ⇒ 对抗活塞上行 ⇒ 负功。
# 一个干净的判据：当「燃烧放热所对应的放热角」超过「可用膨胀角」时，净功开始掉。
print("  ① 先看「燃烧持续角」——这是提前角的天花板之一")
print("     氢层流火焰速度 ≈ 2–3 m/s（远高于汽油），燃烧持续角很短：")
for rpm, deg in ((1150, 10), (3000, 20)):
    print("     经验值：@%d r/min，主燃烧持续约 %d° CA ⇒ 耗时 %.2f ms"
          % (rpm, deg, ms_per_deg(rpm) * deg))

print("\n  ② 再算「燃烧能在负压窗内完成吗」——这才是老师的原意")
print("     若燃烧后要等冷凝，需要 **≥ 2650 ms**；")
print("     而氢的燃烧本身只持续 **1.4 – 3.0 ms** ⇒ 早已结束。")
print("     ⇒ 缸内只剩「已燃高温水蒸气 + 不凝 N₂」，等它慢慢冷却收缩。")
r("燃烧时长 vs 冷凝时长", "1.4–3.0 ms  vs  2650 ms ⇒ 差 %.0f 倍"
  % (2650 / 2.0))

print("\n  ③ 相位上限：提前角过大会把燃烧推进压缩冲程（负功）")
print("     定容理想循环里，点火提前的收益在达到 MBT（爆震/摩擦边界）后转为损失。")
print("     ★ 经验规律：**MBT 通常在上止点前 10–35° CA**（汽油机）；")
print("       氢的火焰更快 ⇒ MBT 更靠近上止点 ⇒ **可用提前角反而更小**。")
print("     ⇒ 「提前 8°」**处在这个合理区间内**（所以方向上完全对）；")
print("       但「提前到 80°」已远超 MBT ⇒ 会大幅损失效率（圈内 80° 那台还声称「温度表从未离开零位」，")
print("       是另一个独立的反常现象，不是正时能解释的）。")
r("汽油机 MBT 典型区间", "BTDC 10–35° CA（氢因火焰快而更靠后）")
r("8° 的位置", "落在合理区间内 ✅（方向对）")
r("80° 的位置", "远超 MBT（圈内数值，会损效率）")

print("\n  ★★ 结论：提前角**不能**换来 2650 ms —— 因为：")
print("     (a) 时间的**量级**就不对（8° = 1.16 ms vs 需要 2650 ms）；")
print("     (b) 提前角受 **MBT 上限**约束，不能为「等冷凝」而无限前移；")
print("     (c) 燃烧本身只有几毫秒，**提前多久都好不了这个量级差**。")


# =====================================================================
sec("Q9  真能缩短时间尺度的手段（若老师要往下走）")
# =====================================================================
print("    ① ★★ **直接喷水/喷水雾** —— 液滴蒸发由表面积驱动，远比整体降温快")
print("       （库内 12 号文档 §四 已指出这是「唯一例外」）")
print("    ② **提高缸内表面积/体积比**（多孔介质、蓄热网、湍流促进器）")
print("    ③ **降低转速**（功率会掉，且要降到 %.0f r/min 量级，不现实）" % rpm_need)
print("    ④ **外部冷凝器 + 长管路**（那就不是缸内做功了）")
print("\n  ★ **提前角不在这个列表里** —— 它改变的是「点火时刻」，不是「传热速率」。")

print("\n  ★ 液滴蒸发时间量级（d² 定律 τ ≈ ρ_l·d² / (8·ρ_g·D·ln(1+B))）")
rho_l, rho_g, D_vap, B_sp = 1000.0, 0.6, 1e-5, 1.0
print("     取 ρ_l=%.0f kg/m³, ρ_g=%.1f, D=%.0e m²/s, B=%.1f" % (rho_l, rho_g, D_vap, B_sp))
for d_um in (10, 20, 50, 100):
    d = d_um * 1e-6
    tau = rho_l * d * d / (8 * rho_g * D_vap * math.log(1 + B_sp))
    print("     液滴 %3d μm ⇒ 蒸发时间 ≈ %7.3f ms" % (d_um, tau * 1000))
r("10 μm 液滴蒸发时间", "≈ %.1f ms（与发动机循环同量级 ✅）"
  % (rho_l * (10e-6) ** 2 / (8 * rho_g * D_vap * math.log(2)) * 1000))


