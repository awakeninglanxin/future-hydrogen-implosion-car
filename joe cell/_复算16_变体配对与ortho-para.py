print("""
  → 若要把 H₂ 的 3:1 解释成「配对 I 比配对 II 常见 3 倍」，需要**额外机制**。
    假设本身没有提供这个机制，所以这一项是**未配套**（不是被证否，是缺件）。

  ★ 这里有个值得留心的现象：**「1 : 1」在两处出现，但来路不同。**
      · 假设给出的 1:1  = 两种配对的等概率（对 H₂ 是错的）
      · 液态水实测的 1:1 = 氢键导致 ortho/para 偏离 3:1（对水是对的）
    下一节专门处理这两条「1:1」的关系。
""")

# ============================================================ ⑥ ★★ 两条 1:1
hr("⑥ ★★ 两条「1 : 1」是否同源？（本轮最深的一层）")

print("""
  把两条线索并排：

     线索甲（圈内档案 · 09 笔记，1932 年观察）：
         「在 H₂O 分子中，一个氢原子属于第一种变体，另一个属于第二种变体。」
         → 若每个水分子都如此，宏观上「两种变体 ≈ 1 : 1」

     线索乙（主流物理 · 液态水）：
         液态水的 ortho : para ≈ **1 : 1**（水蒸气才是 3:1）
         原因：氢键使体系远离统计权重给出的平衡值
         来源：Springer 2024、water-science、arXiv 2210.16149 一致记载 ✅

  ★★ 两条「1:1」说的**可能是同一件事** ——
      微灵视在 1932 年"看到"的「两个 H 不一样」，很可能**就是** ortho/para 本身：
      · 他们观察到的是**真实存在的效应**（液态水里 ortho:para 确实偏离 3:1、接近 1:1）
      · 但把它**解释成「两种不同的原子」**，而实际是**同一原子的两种自旋取向**

  → 这比 09 §4.2 写的「数字巧合」更精确。准确的说法是：
      **不是巧合，而是「同一事实、两种解读」** ——
      他们看到的对象是对的，**错的只是层级归属**（把分子层的自旋关系读成了亚原子层的结构差异）。
""")

print("  ⚠️ 但仍存一个未解项，必须标出来：")
print("""
     · 他们说的是 **H₂O**（水）里的两个 H
     · 液态水的 1:1 是**宏观系综**的比例（无数水分子，各分子本身仍是 3:1 的态分布）
     · 一个水分子内部「这两核自旋平行还是反平行」**本身就是 ortho/para 的定义**
     → 所以「每分子各一」与「系综 1:1」**不是同一句话**：
         前者若指「每个分子都反对称（para）」→ 那应是 **100 % para**，不是 1:1
         只有当它指「系综里两类分子各半」→ 才等于 1:1
     → 档案原文太简略，**无法确定它指的是哪一个** ⚪ 存疑
""")

# ============================================================ ⑦ D₂O 对照
hr("⑦ ★ D₂O 对照组：一个能一举定性的查证方向")

print("""
  如果「两条 1:1 同源」成立（即微灵视看到的 = ortho/para），
  那么把它套到**重水 D₂O** 上，应该看到什么？

  D₂O 的核自旋异构（外网核实 ✅）：
     · 氘核（deuteron）自旋 I = 1，是**玻色子**（H 的质子是费米子）
     · 玻色子 → 对称性要求**反过来**：ortho 对应**偶数** J、para 对应**奇数** J
     · 基态（J=0）是 **ortho**（H₂ 里基态是 para —— 完全相反）
     · 室温 ortho : para = **2 : 1**（不是 3:1，也不是 1:1）
     · ortho 与 para 最低能级差 12.117 cm⁻¹（D₂¹⁶O）
""")

print("  → 于是得到一条**可判定的定性预言**：")
print("""
      若档案里对 **D₂O** 的记录仍是「两个 D 一个属变体 1、一个属变体 2」（1:1），
          → 说明他们的「两种变体」**不是** ortho/para（因为 D₂O 应为 2:1）

      若档案里对 D₂O 的记录变成「2:1」（或指出与 H₂O 不同），
          → 那就**强烈支持**「他们看到的就是 ortho/para」

  ★★ 这是一条**能一举定性的查证方向** —— 不需要新实验，
     只需在微灵视档案（OC 及其附录）里**检索有没有重水 / 氘的观察记录**，
     看它给的配比是 1:1 还是 2:1。
""")

