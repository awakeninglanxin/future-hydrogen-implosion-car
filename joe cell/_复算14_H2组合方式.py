print("    · 20 K 平衡           ：几乎全为 para")
print("    · 「正常氢」（室温久置）：约 75% ortho / 25% para")
print("\n  ★ 与笔记主张对照：")
print("    · 主流 确实存在「两种氢」→ 这一点上**方向一致** ✅")
print("    · 但 H₂ 气体中的比例是 3:1，不是 1:1 ❌")
print("    · 区别在**核自旋取向**（可测），不在「Anu 正负」（不可测）⚪")

print("\n  ★★ 一个惊人的巧合（本项最值得记录的一点）：")
