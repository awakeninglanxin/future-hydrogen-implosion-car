"""
_复算14_H2组合方式.py
====================
对 ima 笔记《H₂ 的组合方式：不是两个相同的变体，而是各取其一》
中出现的可核验断言做独立复算。

复算四项：
  ① Phillips 第二方案 pp → d + π⁺ 的 Q 值与阈值动能
     （并与主流通道 p+p→d+e⁺+νₑ 对照）
  ② 「整体略偏正」与 H₂ 电中性 / 零偶极矩的矛盾
  ③ ortho-H₂ / para-H₂：主流物理里真实的「两种氢」，比例是 3:1
  ④ H₂ 两质子的「全同性」——比 08 文档更锐利的一条

约定：Q = Σm(初) − Σm(末)。Q>0 放热，Q<0 吸热。
运行：python _复算14_H2组合方式.py
"""
import sys

sys.stdout.reconfigure(encoding="utf-8")

U_MEV = 931.49410242      # 1 u 对应的能量 MeV（CODATA 2018）


def hr(title):
    print("\n" + "=" * 70)
    print(title)
    print("=" * 70)


# ---------------------------------------------------------------- 核质量（MeV/c²，PDG）
M_P = 938.2720813
M_N = 939.5654133
M_D = 1875.612928
M_PIP = 139.57039
M_E = 0.51099895

# ---------------------------------------------------------------- 原子质量（u，CODATA）
A_H1 = 1.00782503207     # ¹H 原子
A_H2 = 2.0141017778      # ²H(D) 原子
A_HE4 = 4.00260325413    # ⁴He 原子

hr("① Phillips 第二方案：p + p → d + π⁺")

m_in = 2 * M_P
m_out = M_D + M_PIP
Q1 = m_in - m_out          # 正确约定：初 − 末
print("  反应式    ：p + p → d + π⁺")
print(f"  初态质量  ：2 × {M_P:.6f} = {m_in:.6f} MeV")
print(f"  末态质量  ：{M_D:.6f} + {M_PIP:.6f} = {m_out:.6f} MeV")
print(f"  Q 值      ：{Q1:+.4f} MeV   →  {'放热' if Q1 > 0 else '吸热 ❌ 需输入能量'}")

# 实验室系阈值（靶质子静止）
#   非相对论近似：T_th = |Q|·(Σm_末 + Σm_初)/(2·m_靶)
#   精确相对论式：T_th = [(Σm_末)² − (Σm_初)²] / (2·m_靶)
T_TH_NR = abs(Q1) * (m_out + m_in) / (2 * M_P)
T_TH_EXACT = (m_out ** 2 - m_in ** 2) / (2 * M_P)
print(f"  阈值动能：非相对论近似 {T_TH_NR:.1f} MeV")
print(f"            精确相对论式 {T_TH_EXACT:.1f} MeV")
print(f"  文献对照：pp→dπ⁺ 实验阈值 ≈ 287.5 MeV（TRIUMF / PSI / COSY）")
print(f"  → 两式相差 {abs(T_TH_EXACT-T_TH_NR):.2f} MeV（{abs(T_TH_EXACT-T_TH_NR)/T_TH_EXACT*100:.2f}%）")
print(f"  → 精确式 {T_TH_EXACT:.1f} MeV  ✅ 与实验值吻合")
print("    （质子质量 938 MeV 已接近相对论区，此处应取精确式）")
T_TH = T_TH_EXACT

hr("①-b 对照主流通道：p + p → d + e⁺ + νₑ（弱作用，太阳第一步）")

# 用原子质量口径最简洁（正电子会与电子湮灭）
Q2 = U_MEV * (2 * A_H1 - A_H2)
print("  用原子质量口径（含电子，正电子湮灭后等价）：")
print(f"    2·m(¹H) − m(²H) = {2*A_H1:.8f} − {A_H2:.8f} = {2*A_H1-A_H2:.8f} u")
print(f"    Q = {2*A_H1-A_H2:.8f} × {U_MEV} = {Q2:+.4f} MeV")
print(f"  文献值    ：+1.442 MeV（质子-质子链第一步）  → 复算 {Q2:.3f} MeV  ✅")

# 核质量口径交叉验算（+ 2m_e 湮灭能）
Q2n = (2 * M_P - M_D - M_E) + 2 * M_E
print(f"  交叉验算（核质量口径 + 正电子湮灭 2mₑ）：{Q2n:+.4f} MeV  ✅ 同值")

print("\n  ★ 同一末态核（d）、两个通道的对比：")
print(f"     · 主流  pp→d e⁺νₑ ：Q = {Q2:+.3f} MeV（自发放热，太阳每秒 6×10¹¹ kg）")
print(f"     · Phillips pp→d π⁺ ：Q = {Q1:+.3f} MeV（必须外界注入）")
print(f"     · 差距  ：{abs(Q1)/abs(Q2):.0f} 倍，符号相反")

hr("①-c 与氢的化学能量级比较")

EV_PER_KJMOL = 1.0 / 96.485      # 1 eV/分子 = 96.485 kJ/mol
E_BOND = 436.0 * EV_PER_KJMOL    # H₂ 键能
E_VIB = 4401.21 * 1.23984193e-4  # ωₑ = 4401.21 cm⁻¹ → eV
T_TH_eV = T_TH * 1e6

print(f"  H₂ 键能（436 kJ/mol）      ：{E_BOND:.3f} eV")
print(f"  H₂ 振动量子（ωₑ=4401.21cm⁻¹）：{E_VIB:.4f} eV")
print(f"  pp→dπ⁺ 阈值动能            ：{T_TH_eV:.3e} eV")
print(f"  → 与键能之比               ：{T_TH_eV/E_BOND:.3e} 倍（约 {T_TH_eV/E_BOND/1e8:.1f} 亿倍）")
print(f"  → 与振动能之比             ：{T_TH_eV/E_VIB:.3e} 倍（约 {T_TH_eV/E_VIB/1e8:.1f} 亿倍）")
print("\n  ★ 结论：该通道与「化学/微灵视观察」的能量尺度相差 8 个数量级 ——")
print("    它不是「观察者不易察觉的小扰动」，而是必须先有一台 288 MeV 加速器。")

hr("② 「整体略偏正」 vs H₂ 的电中性")

print("  笔记原话：「一中性 + 一偏正 → 整体略偏正，")
print("              这可能正是化学键合中吸引力的来源」")
net1 = 9 - 9
net2 = 10 - 8
print(f"\n  按笔记自述计法：变体1 净 Anu 电荷 = {net1:+d}，变体2 = {net2:+d}")
print(f"  H₂ = 变体1 + 变体2  →  分子净 Anu 电荷 = {net1+net2:+d}")

print("\n  主流实测：")
print("    · H₂ 永久电偶极矩 μ = 0（同核双原子，D∞h，无红外活性）")
print("    · 纯 H₂ 不导电、不受外电场偏转 → 净电荷严格为 0")
k_e = 8.9875517923e9      # N·m²/C²
E_EL = 1.602176634e-19    # C
K_B_EV = 8.617333262e-5   # eV/K
r_m = 0.074e-9            # H₂ 键长 74 pm
# 每个「净 +2e」，两个分子之间为 +2 × +2 = 4e²
U_J = k_e * 4 * E_EL ** 2 / r_m
U_eV = U_J / E_EL
print("    若真有净 +2e，两个 H₂ 之间的库仑排斥：")
print(f"        U = k·(2e)(2e)/r = {U_eV:.1f} eV   （r = 74 pm）")
print(f"        → 是 H₂ 键能（{E_BOND:.2f} eV）的 {U_eV/E_BOND:.0f} 倍")
print(f"        → 等效温度 T = U/k_B = {U_eV/K_B_EV:.2e} K（约 {U_eV/K_B_EV/1e6:.1f}×10⁶ K）")
print("        → 这个排斥力会在任何常温条件下把 H₂ 直接炸开")
print("  ★ 结论：**净 +2 电荷** 与 **H₂ 是稳定的非极性分子** 不能同时成立 ❌")

hr("③ ortho-H₂ / para-H₂：主流物理里真实的「两种氢」")

print("  H₂ 核自旋异构体（1929 年由光谱学确认，完全可测量）：")
print("    · ortho-H₂：两质子核自旋平行，I=1（三重态），统计权重 3")
print("    · para-H₂ ：两质子核自旋反平行，I=0（单态），统计权重 1")
print("\n  比例（由统计权重 + 零点能差决定）：")
