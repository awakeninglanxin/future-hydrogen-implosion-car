"""
_复算15_质子含多少Anu.py
========================
对 ima 笔记《碳-12 的 Anu 数量：216 个》做独立复算。

起点（老师提问）：ortho/para 指两个氢核自旋的相对取向，每个氢核是质子。
  那么「传统科学的质子」到底对应多少个 Anu？

复算项：
  ① 碳-12 结构式 4 + 4C27 + 4C26 的加总
  ② OC 的换算规则：number weight = Anu 数 / 18（18 = 氢的 Anu 数）
  ③ ★ 核心：质子 = 多少 Anu？两种口径（18 vs 9）的差别
  ④ ★★ 关键：「216 ÷ 18 = 12」能否区分这两种口径？—— 不能（退化）
  ⑤ ★★ 更深：「= 12.00 精确吻合」里有多少是真内容？（定义恒等式分解）
  ⑥ 「每核子 Anu 数」这个常数，用 OC 表里几个元素交叉验证

约定：圈内口径 ↔ 主流实证分轨并列，各标证据强度。
运行：python _复算15_质子含多少Anu.py
"""
import sys

sys.stdout.reconfigure(encoding="utf-8")


def hr(title):
    print("\n" + "=" * 72)
    print(title)
    print("=" * 72)


# ================================================================ ① 碳-12 结构式
hr("① 碳-12 结构式：碳 = 4 + 4C27 + 4C26")

N_CENTER = 4                 # 中央球体 4 个 Anu
N_C27 = 27                   # 每个 C27 漏斗 27 个 Anu
N_C26 = 26                   # 每个 C26 漏斗 26 个 Anu
K_FUNNEL = 4                 # 每种漏斗各 4 个

tot_c27 = K_FUNNEL * N_C27
tot_c26 = K_FUNNEL * N_C26
TOT_C = N_CENTER + tot_c27 + tot_c26

print(f"  中央球体        ：{N_CENTER} 个")
print(f"  漏斗 A（4 × C27）：4 × {N_C27} = {tot_c27}")
print(f"  漏斗 B（4 × C26）：4 × {N_C26} = {tot_c26}")
print(f"  ─────────────────────────────")
print(f"  合计            ：{TOT_C} 个 Anu")
print(f"  （注：'C27'/'C26' 是漏斗型号名，指的是该漏斗含 27 / 26 个 Anu）")
print("\n  旁证：8 个漏斗（八面体 8 个面）+ 中央球体 → 碳的价数为 4")
print(f"        磷等元素同理：漏斗数 = 2 × 价数（Phillips 的规则）")

# ================================================================ ② OC 换算规则
hr("② OC 的换算规则：number weight = Anu 数 / 18")

N_H = 18                     # 氢的 Anu 数 —— 这个 18 是关键
print("  《Occult Chemistry》原文（转录）：")
print('    "We take Hydrogen=18 Anu as our standard and equal to 1."')
print('    "The relation between our weights and that of the International')
print('     Tables can be found by adjusting our weights to the standard of')
print('     H = 1.0078."')
print()
print(f"  → 18 不是一个物理常数，而是**氢的 Anu 计数**")
print(f"  → number weight := Anu 数 ÷ {N_H}")

w_C = TOT_C / N_H
print(f"\n  碳：{TOT_C} ÷ {N_H} = {w_C:.2f}")
print(f"      OC 表中同时给出化学值 11.91 与 Anu 比值 12.00")
print(f"      差异来源：OC 取 H=1.000，国际表取 H=1.0078（差 0.78%）")

# ================================================================ ③ 质子 = 多少 Anu
hr("③ ★ 核心：传统科学的质子 = 多少 Anu？")

print("  先摆主流事实（无争议）：")
print("    · 质子 = u u d，共 3 个夸克，电荷 +2/3 +2/3 −1/3 = +1")
print("    · 中子 = u d d，共 3 个夸克，电荷 +2/3 −1/3 −1/3 = 0")
print("    · 原子量单位 u 的定义：C-12 的质量 ≡ 12 u（人为约定）")
print("    · 因此 1 u ≈ 1 个核子的质量（质子 1.00728 u，中子 1.00866 u）")
print()

print("  再摆 Phillips 的 omegon 模型（1980《ESP of Quarks》）：")
print("    · UPA（= Anu）被认定为「亚夸克」，命名 omegon")
print("    · 每个夸克 = 3 个 omegon  →  每个核子 = 3 × 3 = 9 个 omegon")
print("    · 氢原子 = 9 个亚夸克（= 1 个质子）；其实观察到的氢 MPA 有两个三角")
print("    · 碳 MPA「由两个 C-12 核形成，提供 216 个亚夸克，与 UPA 数相同」")
print()

print("  ── 两种口径 ──")
print()
print("  口径 A（OC 原始，朴素）：")
print(f"    1 个原子量单位 = {N_H} 个 Anu")
print(f"    若把「1 原子量单位 ≈ 1 个核子」（氢 H=1）⇒ 1 核子 = {N_H} 个 Anu")
print()
print("  口径 B（Phillips omegon）：")
print("    1 核子 = 3 夸克 × 3 亚夸克 = 9 个 Anu")
print("    因为观察到的「氢 MPA」（18 Anu）其实是 2 个质子 → 18 / 2 = 9")
print()
print("  ★ 两者相差恰好一个因数 2：")
print(f"    {N_H} = 2 × 9")
print("    而这个 2，正是 Phillips 不得不引入的假设 ——")
print("    「他们每次看到的其实是两个核融合在一起」（原文 *two atoms that had")
print("     somehow fused together*）")
print()
print("  ★★★ 所以，回答老师的问题：")
print("    · 按 Phillips 口径：**质子 = 9 个 Anu**")
print(f"    · 按 OC 朴素口径：1 核子 = {N_H} 个 Anu（= 2 个 9）")
print("    · 二者不能同时成立；差的那个 2 是模型假设，不是观测")

# ================================================================ ④ 216 能否区分
hr("④ ★★ 关键：碳的 216 能不能区分「18」与「9」两种口径？")

# 碳-12 的核子数
A_C12 = 12                    # 6 p + 6 n
MPA_NUCLEI = 2 * A_C12        # Phillips：观察到的是「2 个碳核」

via_18 = A_C12 * N_H
via_9 = MPA_NUCLEI * 9

print(f"  碳-12 的核子数            ：{A_C12} 个（6 质子 + 6 中子）")
print(f"  Phillips 说看到的核数      ：2 × {A_C12} = {MPA_NUCLEI} 个")
print()
print(f"  口径 A 算法：{A_C12} × {N_H} = {via_18}")
print(f"  口径 B 算法：{MPA_NUCLEI} × 9 = {via_9}")
print()
print(f"  → 两条路都得 **{TOT_C}**，与 OC 计数一致 ✅")
print()
print("  ★★★ 结论：**216 完全不能区分这两种口径。**")
print("     因为 12 × 18 = 24 × 9 —— 因数 2 从分母挪到了分子。")
print("     换言之，`216 ÷ 18 = 12` 这个算式，**天然无法告诉你**")
print("     「1 个核子是 18 个 Anu」还是「9 个 Anu」。")
print()
print("     → 这是判据五「同族量之比」的又一样本，且比 D₀/Dₑ 那个更隐蔽：")
print("       D₀/Dₑ 是同一个量差一个零点能；这里是同一个积差一个因数 2。")

# ================================================================ ⑤ 定义恒等式
hr("⑤ ★★ 更深：「216 ÷ 18 = 12.00 精确吻合」里有多少真内容？")

print("  把这个等式拆开看：")
print()
print("        碳的 Anu 数     216       碳的原子量    12")
print("        ───────────  =  ───   ⟺   ──────────  =  ───")
print("        氢的 Anu 数      18       氢的原子量     1")
print()
print("  两边交叉相乘，得到等价形式：")
print()
print("        碳的 Anu 数       氢的 Anu 数")
print("        ──────────   =   ──────────")
print("        碳的原子量         氢的原子量")
print()
print(f"        {TOT_C} / {A_C12} = {TOT_C/A_C12}")
print(f"        {N_H} / 1 = {N_H}")
print()
print("  ★ 也就是说，`216 ÷ 18 = 12` 只等价于一句话：")
print("     「**每个原子量单位对应的 Anu 数是一个常数**」（= 18）")
print()
print("  → 它检验的只有一件事：**Anu 的质量是否处处相同**")
print("  → 它**不能**证明：")
print("     ① Anu 真实存在")
print("     ② 1 个核子 = 18 还是 9")
print("     ③ Anu 就是夸克 / 亚夸克")
print()
print("  ── 再加一层：12 这个数本身也是「定义」出来的 ──")
print("     主流化学里 **C-12 的原子量 ≡ 12 是人为约定**（u 的定义）")
print("     OC 把氢定为 1，碳算出恰好 12")
print("     → 一个锚在氢、一个锚在碳，两头都是「定义」")
print("     → 所以「精确吻合」是**双重定义性**的，说服力远小于字面观感")
print()
print("  ── 那还有没有真内容？有，但很弱 ──")
print("     真内容 = 「Anu 计数 ∝ 原子量」这个经验规律")
print("     它说明：Anu 的质量大致均匀（否则比值不会线性）")
print("     这是**一致性检验**，不是**存在性证明**")
print("     ⚠️ 且对任何「均匀子单元」的计数方案都会自动成立")

# ================================================================ ⑥ 每核子 Anu 数交叉验证
hr("⑥ 「每核子 9 Anu」用 OC 表里几个元素交叉验证")

# OC 表中给出的（元素, OC Anu 数, 主流原子量, 核子数=取整A）
# 数据来源：Occult Chemistry 正文（BookRags / Project Gutenberg 转录）
DATA = [
    # 名称,      OC Anu 数, 主流 A,  核子数(取整)
    ("氢 H",      18,      1.008,   1),
    ("碳 C",      216,     12.011,  12),
    ("铍 Be",     164,     9.012,   9),
    ("钙 Ca",     720,     40.078,  40),
]

print("  （Phillips 模型预言：MPA 含 2 个核 → 预言 Anu 数 = 2 × 核子数 × 9）")
print()
print(f"  {'元素':<10}{'OC 计数':>8}{'主流 A':>9}{'核子数':>8}{'模型预言':>10}{'差':>8}{'吻合':>6}")
print("  " + "-" * 62)
for name, anu, A, nuc in DATA:
    pred = 2 * nuc * 9
    diff = anu - pred
    ok = "✅" if diff == 0 else "❌"
    print(f"  {name:<10}{anu:>8}{A:>9.3f}{nuc:>8}{pred:>10}{diff:>+8}{ok:>6}")

print()
print("  ★ 读数：")
print("    · 氢、碳 → 完全吻合（差 0）→ 这正是笔记说的「少数完全吻合的元素」")
print("    · 铍 164 vs 预言 162 → 差 2；且 164 不是 9 的倍数（164/9 = 18.22）")
print("    · 钙 720 vs 预言 720 → 吻合 ✅（但 720 = 18 × 40，也无法区分 18 vs 9）")
print()
print("  ⚠️ 注意一个统计陷阱：OC 的计数**天然接近** 18 × A（因为比率被定为 18）")
print("     所以「差 0」的元素，并不能排除「这个吻合是归一化带来的」")
print("     真正有判别力的只有**不是 9 的倍数**的计数（如铍 164）")
print("     → 而铍恰恰**不吻合**")

