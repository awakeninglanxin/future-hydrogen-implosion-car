def fuel_case(name, base, hho, lhv, dist=100.0, speed=60.0, alt=None):
    save_l = dist / base - dist / hho
    save_mj = save_l * lhv
    v = save_mj * 1000.0 / E_LHV
    kwh = save_mj * 1000.0 / 3600.0
    hours = dist / speed
    p_min = kwh / hours
    p_real = (v * 1000 / CCW / 1000) / hours
    print(f"  ── {name} ──")
    print(f"    标称油耗：{base} → {hho} km/L，改善 {(hho-base)/base*100:.1f}%"
          + (f"（对照 {alt}）" if alt else ""))
    print(f"    {dist:.0f} km 省 {save_l:.3f} L = {save_mj:.1f} MJ")
    print(f"    若节油全部折算为 HHO 供热：需 HHO {v:.0f} L = {v*1000:.0f} mL")
    print(f"    100% 效率最小电功 = {kwh:.2f} kWh；按 {speed:.0f} km/h → **{p_min:.1f} kW**")
    print(f"    若按 37 cc/Wh 实测效率 → {p_real:.1f} kW 电解输入功率")
    print(f"    车载 12 V 发电机典型 1.2 kW → 缺口 {p_min/1.2:.0f} ~ {p_real/1.2:.0f} 倍")
    print()

