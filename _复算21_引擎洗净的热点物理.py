def q1_mie():
    """Q1 · 最小点火能：氢是不是真的比汽油低一个量级？"""
    banner("Q1 · 氢的最小点火能 vs 传统燃料（老师那句「洗干净」的第一条物理理由）")
    h2 = MIE["氢 H2"]
    for name, v in MIE.items():
        ratio = v / h2
        note = ""
        if name == "汽油":
            note = f"  ← 氢是汽油的 1/{ratio:.1f}"
        print(f"  {name:<10} {v:>6.3f} mJ   相对氢 {ratio:>6.1f} 倍{note}")
    print(f"\n  氢的着火极限（体积分数）: {FLAM_LOW:.0f}% – {FLAM_HIGH:.0f}%"
          f"   ⇒ 可燃范围宽 {FLAM_HIGH/FLAM_LOW:.1f} 倍")
    print("  汽油着火极限约为 1.4% – 7.6%   ⇒ 可燃范围宽 5.4 倍")
    r_gas = 7.6 / 1.4
    print(f"  ⇒ 氢的可燃范围是汽油的 {((FLAM_HIGH-FLAM_LOW)/(7.6-1.4)):.1f} 倍（区间宽度之比）")
    print("\n  ★ 结论：氢只需汽油约 1/14 的能量即可点燃，且可点燃的浓度窗口宽一个量级。")
    print("     ⇒ 任何『在汽油/柴油上无害』的微小热点，对氢都可能是点火源。")


def q2_temperature():
    """Q2 · 压缩终了温度 vs 各燃料自燃点，以及积碳是否构成热点"""
    banner("Q2 · 压缩终了温度 vs 自燃点（积碳为什么能成为热点）")
    gamma = 1.4
    def t2(cr, t1=T0):
        return t1 * (cr ** (gamma - 1))

    print("  绝热压缩终了温度（进气 25 °C, γ=1.4）:")
    for cr in (14, 16, 18, 20, 22, 24, 28):
        print(f"    CR {cr:>2}  →  {t2(cr)-273.15:>7.1f} °C")

    print("\n  各燃料自燃点:")
    for name, t in T_AUTO.items():
        print(f"    {name:<10} {t-273.15:>7.1f} °C")

    cr_h2 = (T_AUTO["氢 H2"] / T0) ** (1.0 / (gamma - 1))
    cr_di = (T_AUTO["柴油"] / T0) ** (1.0 / (gamma - 1))
    print(f"\n  ⇒ 压燃氢所需绝热压缩比 CR ≈ {cr_h2:.2f}（柴油只需 CR ≈ {cr_di:.2f}）")
    print("    即：柴油机的压缩比『温度上够得着』氢的自燃点 —— 但请看 Q3，差距在时间。")

    print("\n  ★ 积碳成为热点的机理（三条同时成立才构成热点）:")
    print("    ① 积碳层导热差 ⇒ 隔热 ⇒ 缸壁散热受阻 ⇒ 局部表面温度高于清洁表面")
    print("    ② 积碳比热×密度低 ⇒ 储热少但放热也慢 ⇒ 在进气/压缩早期仍保有上一循环余热")
    print("    ③ 表面粗糙、比表面大 ⇒ 微区温度集中")
    t_di = T_AUTO["柴油"] - 273.15
    print(f"    ⇒ 关键：**柴油残留/机油雾滴的自燃点只有 {t_di:.0f} °C**，")
    print(f"      它们会在氢（{T_AUTO['氢 H2']-273.15:.0f} °C）**之前**先着火，")
    print("      成为点火源，引发氢的预点火与回火。")


def q3_timescale():
    """Q3 · 颗粒热平衡时间尺度（积碳是「同温」还是「滞后」？）"""
    banner("Q3 · 积碳颗粒的热响应时间 —— 它是与气体同温，还是独立热点？")
    print("  热扩散时间 τ ≈ r² / α,  α = k / (ρ·c)\n")
    print(f"  {'材料':<18}{'α (m²/s)':>14}{'τ @ r=1μm':>14}{'τ @ r=10μm':>14}{'τ @ r=100μm':>15}")
    for name, (k, rho, c) in MAT.items():
        alpha = k / (rho * c)
        row = f"  {name:<18}{alpha:>14.3e}"
        for r_um in (1, 10, 100):
            r = r_um * 1e-6
            tau = r * r / alpha
            if tau < 1e-3:
                s = f"{tau*1e6:.2f} μs"
            elif tau < 1.0:
                s = f"{tau*1e3:.2f} ms"
            else:
                s = f"{tau:.3f} s"
            row += f"{s:>14}"
        print(row)

    print("\n  ★ 关键推论（注意区分两件事：『它自己多热』vs『它改变了什么』）：")
    print("    · 石墨颗粒（10 μm）τ ≈ 1.6 μs ≪ 压缩冲程 ~10 ms")
    print("      ⇒ 颗粒与周围气体**快速同温**。但★注意：")
    print("        『与气体同温』**不等于无害** —— 它意味着颗粒不构成一个")
    print("        长期偏热的独立热源，但**贴壁边界层本来就更热**，")
    print("        颗粒只是把该处的热量传来传去（快速跟随），既不额外加热、也不额外冷却。")
    print("        ⇒ 真正的问题是它**改善了局部传热**并提供了**催化/反应表面**。")
    print("    · 柴油烟灰层（导热仅 0.3 W/m·K）α 低 2 个量级 ⇒ 热扩散慢、**起隔热作用**。")
    print("      ⇒ 它的危害是『把缸壁的散热挡在外面』，")
    print("        使**贴壁气体层**温度升高 ⇒ 该处氢混合气更易自燃。")
    print("    · 机油雾滴：自燃点最低（约 200–250 °C），且是**液体** ⇒ 蒸发/裂解后")
    print("      生成碳氢自由基 ⇒ 成为**化学**点火源（不只是热源）。")
    print("      ★ 这是三类里最危险的一类：它的自燃闸门**最低**。")

    # 压缩冲程时间尺度
    print("\n  压缩冲程时间尺度（用于对照）:")
    for rpm in (1200, 2000, 3000):
        t_stroke = 60.0 / rpm / 2.0 * 1000.0   # 四冲程：半圈 ≈ 压缩冲程
        print(f"    {rpm:>4} r/min ⇒ 压缩冲程约 {t_stroke:.1f} ms")
    print("  氢在 600–700 °C 区间的点火延迟 ≈ 1–10 ms（10⁻³–10⁻² s）")
    print("  ⇒ ★ 两者**同一量级** ⇒ 『温度够』不等于『来及得着』——")
    print("    这正是 §11.0.1 说『工程要求 CR>20』的原因：靠更高温缩短点火延迟。")
    print("    （与判据⑨『时间尺度判据』同源）")


def q4_hydro_decarb():
    """Q4 · 氢脱碳的化学热力学 —— 主流为什么真能用氢洗引擎？"""
    banner("Q4 · ★ 氢脱碳（hydrogen decarbonization）的化学基础")
    # 标准生成焓 kJ/mol @298K
    dHf = {"CH4": -74.87, "C(石墨)": 0.0, "H2": 0.0, "CO": -110.53, "CO2": -393.51}
    dHf_H2O_g = -241.82

    print("  ① 碳加氢生成甲烷（活性氢 H· 除碳的核心反应）")
    dH = dHf["CH4"] - dHf["C(石墨)"] - 2 * dHf["H2"]
    print(f"     C(s) + 2H₂(g) → CH₄(g)     ΔH° = {dH:+.2f} kJ/mol（放热）")
    print(f"     ⇒ 热力学上自发（ΔH<0），且产物是**气体** ⇒ 随排气带走。")

    print("\n  ② 碳的水煤气反应（高温下与水蒸气/CO₂ 反应）")
    dH_wg = dHf["CO"] + dHf["H2"] - dHf["C(石墨)"] - dHf_H2O_g
    print(f"     C(s) + H₂O(g) → CO(g) + H₂(g)   ΔH° = {dH_wg:+.2f} kJ/mol（吸热）")
    dH_bd = dHf["CO2"] - dHf["C(石墨)"] - 0.0
    print(f"     C(s) + O₂(g) → CO₂(g)          ΔH° = {dH_bd:+.2f} kJ/mol（强烈放热）")
    print("     ⇒ 氢燃烧产生**高温水蒸气**，既提供 ② 所需温度，又直接参与反应。")

    print("\n  ③ 为什么『只有氢』特别好用")
    print("     · 氢火焰温度高（绝热火焰温度 ~2,100 °C）、传播快 ⇒ 能把积碳层烧透")
    print("     · 氢是**无碳燃料** ⇒ 自身不产生新的积碳（对照：柴油/汽油会补碳）")
    print("     · 产物仅为水蒸气 ⇒ 不引入灰分、不引入硫磷")
    print("     ⇒ ★ 主流把它做成商用服务：HydroMaverich Ecleaner、Auto-Decarb（ARAI 认证）、")
    print("       1stinrail 25 台车 4 个月实测（油耗/CO₂ 降 15%）。")

    print("\n  ★★ 由此得到本节的**核心洞察（同一物理、两个方向）**：")
    print("     · 方向 A（主流）：用氢**主动清洗**已经积碳的旧发动机  —— 把它做成服务卖")
    print("     · 方向 B（Joe Cell 主张）：装车前**必须预先洗净**  —— 否则残留成热点")
    print("     两者的底层物理是同一套（H· 与碳的反应 / 氢的极低点火能），")
    print("     ⇒ 老师『必须引擎内都要洗干净』与主流实证**方向一致、不冲突**。")


