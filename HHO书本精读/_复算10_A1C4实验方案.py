# =========================================================================
print("\n" + LINE)
print("  复算 ① · 一票否决闸门：1 Ah 到底该产多少 mL HHO？")
print(LINE)
print("""
  法拉第定律：1 mol 电子转移 → 0.5 mol H2、0.25 mol O2
              合计 0.75 mol 气体（H2:O2 = 2:1）
""")

def gas_per_Ah(vm, label):
    C = 3600.0                       # 1 Ah = 3600 C
    n_e = C / F_CONST                # mol 电子
    n_H2 = n_e / 2.0
    n_O2 = n_e / 4.0
    n_tot = n_H2 + n_O2
    V_L = n_tot * vm
    print(f"  【{label}】")
    print(f"    1 Ah = 3600 C → 电子 {n_e:.6f} mol")
    print(f"    H2 = {n_H2:.6f} mol   O2 = {n_O2:.6f} mol   (比 {n_H2/n_O2:.2f}:1) ✅")
    print(f"    总气量 = {n_tot:.6f} mol × {vm:.5f} L/mol = {V_L:.6f} L = **{V_L*1000:.1f} mL**")
    return n_tot, V_L

n_tot_0, V_0 = gas_per_Ah(VM_0C, "0 ℃, 101.325 kPa  ← 书里的 627 mL 就是这个口径")
n_tot_25, V_25 = gas_per_Ah(VM_25C, "25 ℃, 101.325 kPa ← 实验室常温")

print(f"""
  ★★ 关键口径陷阱（这一条不写清楚，整个闸门会失效）：
     0 ℃   → {V_0*1000:.1f} mL   ← 这就是书里 "627 mL" 的来历 ✅ 复算吻合
     25 ℃  → {V_25*1000:.1f} mL
     两者差 {abs(V_25-V_0)/V_0*100:.1f}%

  🔴 若在实验室常温（25 ℃）测出 {V_25*1000:.0f} mL，**不是"超法拉第 9%"**，
     而是**完全正常的法拉第产气**。
     判定时必须先把气量换算到 0 ℃ 标准状态，或把闸门值改成 684 mL。
""")

