# 以 2 L 汽油机、74 kW 输出、热效率 35% 为模型
P_out = 74.0                                  # kW（Nature 论文 Škoda Fabia）
eta_th = 0.35
P_fuel = P_out / eta_th                       # kW 燃料功率
LHV_gasoline = 44.0                           # MJ/kg

# HHO 的体积能值
V_H2_per_L = (1.0 / VM_0C) / 3.0 * 2.0        # 1 L HHO 含 H2 的 mol（0℃）
E_HHO_per_L = V_H2_per_L * LHV_H2             # kJ/L
print(f"  【HHO 体积能值】")
print(f"    1 L HHO (0 ℃,1 atm) 含 H2 = {V_H2_per_L*1000:.3f} mmol")
print(f"    × LHV {LHV_H2} kJ/mol = **{E_HHO_per_L:.3f} kJ/L**")
print(f"    （对照主流：氢-空气混合气 LHV ≈ 3.5 kJ/L，纯氢 ≈ 10.8 kJ/L）")

Q_need_kJ_s = P_fuel                          # kJ/s = kW
Q_need_L_s = Q_need_kJ_s / E_HHO_per_L
print(f"\n  【需求侧】2 L 汽油机输出 {P_out:.0f} kW，热效率 {eta_th*100:.0f}%")
print(f"    所需燃料功率 = {P_out:.0f} / {eta_th} = **{P_fuel:.1f} kW**")
print(f"    若全用 HHO：{P_fuel:.1f} kW ÷ {E_HHO_per_L:.3f} kJ/L")
print(f"              = **{Q_need_L_s:.0f} L/s = {Q_need_L_s*60:.0f} L/min = {Q_need_L_s*3600:,.0f} L/h**")

# 供给侧：车载电解 12 V × 1 A
V_car, I_car = 12.0, 1.0
P_car = V_car * I_car
# 12 W 运行 1 h → Wh / 热中性电压 = Ah
Ah_per_h_at_car = P_car / 1.481
V_supply_L_h = Ah_per_h_at_car * V_0
print(f"\n  【供给侧】车载：{V_car:.0f} V × {I_car:.1f} A = **{P_car:.0f} W**")
print(f"    → 1 h 供 {P_car:.0f} Wh ÷ 1.481 V = {Ah_per_h_at_car:.2f} Ah")
print(f"    → 产气 {Ah_per_h_at_car:.2f} × {V_0*1000:.1f} mL = {V_supply_L_h*1000:.0f} mL/h = **{V_supply_L_h:.2f} L/h**")

gap = (Q_need_L_s * 3600) / V_supply_L_h
print(f"\n  🔴 **缺口 = {Q_need_L_s*3600:,.0f} L/h ÷ {V_supply_L_h:.2f} L/h = {gap:,.0f} 倍**")
print(f"     即约 **{gap:.1e} 倍** —— 与既有报告的「约 10^4 倍」结论**量级一致** ✅")
