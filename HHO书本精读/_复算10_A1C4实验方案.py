# -------------------------------------------------------------------------
# 物理常数（教科书值）
# -------------------------------------------------------------------------
F_CONST = 96485.33212      # 法拉第常数 C/mol
R_GAS = 8.314462618        # 气体常数 J/(mol·K)
M_H2O = 18.01528           # g/mol
M_H2 = 2.01588
M_O2 = 31.998
VM_0C = 22.41397           # 标准摩尔体积 0 ℃, 101.325 kPa  L/mol
VM_25C = 24.46540          # 25 ℃, 101.325 kPa          L/mol

# 氢的热值
LHV_H2 = 241.83            # kJ/mol  (低热值：产物为气态水)
HHV_H2 = 285.83            # kJ/mol  (高热值：产物为液态水)

print(LINE)
