print("\n" + LINE)
print("  复算 ② · 热中性电压的三个口径 —— 全项目最容易搞错的一处")
print(LINE)
print("""
  三个数字都常被称为"水的理论分解电压"，但**物理含义完全不同**：
""")

rows = [
    ("可逆（热力学）电压", 1.229, "ΔG/nF，ΔG = 237.13 kJ/mol", "电解**不会**自发，但也不算反应热"),
    ("热中性电压（LHV）", 1.253, "ΔH_LHV/nF，产物=**气态**水", "电+热总和最低；产气为气态水时"),
    ("热中性电压（HHV）", 1.481, "ΔH_HHV/nF，产物=**液态**水", "★ **真实电解槽（液相）的正解**"),
]
print(f"  {'名称':<22}{'值(V)':<10}{'依据':<38}{'说明'}")
print("  " + SUB[:90])
for name, v, basis, note in rows:
    print(f"  {name:<22}{v:<10.3f}{basis:<38}{note}")

dG = 237.13
dH_HHV = 285.83
dH_LHV = 241.83
print(f"""
  【复算验证】
    ΔG  → {dG*1000:.0f} / ({2}×{F_CONST}) = {dG*1000/(2*F_CONST):.4f} V  ✅ = 1.229 V
    HHV → {dH_HHV*1000:.0f} / (2×{F_CONST}) = {dH_HHV*1000/(2*F_CONST):.4f} V  ✅ = 1.481 V
    LHV → {dH_LHV*1000:.0f} / (2×{F_CONST}) = {dH_LHV*1000/(2*F_CONST):.4f} V  ✅ = 1.253 V

  🔴 **判据用哪个？**
     · 算"**效率**"（产出/投入）→ 用 **1.481 V**（HHV，液相水）
       —— 因为真实电解槽里水是液态进、液态出
       —— 若误用 1.253 V，效率会被**系统性高估 18.2%**
     · 算"**是否超法拉第**"（电荷口径）→ **与电压无关**，只看 mol 电子
       —— 这是 1 Ah → 627 mL 闸门的好处：**它绕过了电压争议**
""")
print(f"  ★ 1.481 / 1.253 = {1.481/1.253:.4f}  → 误用会把效率高估 {(1.481/1.253-1)*100:.1f}%")

# =========================================================================
print("\n" + LINE)
print("  复算 ③ · 效率判据表：不同槽电压对应什么效率")
print(LINE)
print("""
  （以 HHV = 1.481 V 为热中性基准；产出按 HHV 计算化学能）
""")
print(f"  {'槽电压 V':<10}{'输入 Wh/Ah':<14}{'产出 kJ/Ah':<14}{'效率 η':<12}{'判定'}")
print("  " + SUB[:70])
n_H2_Ah = n_tot_0 / 3.0 * 2.0          # 1 Ah 产 H2 的 mol 数
E_out = n_H2_Ah * HHV_H2               # kJ
for V_cell in [1.229, 1.481, 1.80, 2.00, 2.50, 3.00]:
    E_in = V_cell * 3600.0 / 1000.0     # kJ (V×C = J)
    eta = E_out / E_in * 100.0
    if V_cell < 1.481:
        judge = "🟡 低于热中性 → 必为**仪表误差**或**另有热源**"
    elif V_cell < 1.60:
        judge = "✅ 物理上界附近（真实好槽不可能达到）"
    elif V_cell < 2.20:
        judge = "✅ 正常工业范围（η 67–92%）"
    else:
        judge = "⚠️ 效率偏低，属老旧/劣质槽"
    print(f"  {V_cell:<10.3f}{E_in/3.6:<14.2f}{E_out:<14.2f}{eta:<12.1f}{judge}")
print(f"""
  ★ 锚点：1 Ah 产 H2 = {n_H2_Ah:.6f} mol
          × {HHV_H2} kJ/mol = {E_out:.2f} kJ  ← 这就是 1 Ah 的最大化学能产出
  ★ 1.481 V × 1 Ah = 1.481 Wh = 5.33 kJ → η = 100.0%  ✅ 自洽
""")

