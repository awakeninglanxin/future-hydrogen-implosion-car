print("""
  ★ 关键：**中性筒是"两侧都有水"的**（它们浮在环形水格里），
     所以增加中性筒层数 ⇒ **面积近似线性增加**（每多一层，多一圈圆柱的两侧）
""")

sec("Q4  各层间环形水体积")
print(f"  环形体积 V = π(R_out² − R_in²) · H     （1 L = 1e6 mm³）")
print(f"  {'环隙':>26} | {'内径':>7} | {'外径':>7} | {'宽度':>9} | {'水体积':>10}")
print("  " + "-" * 74)
pairs = []
ring_names = [
    ("阴极 ↔ 中性筒1", 1.0, 2.0),
    ("中性筒1 ↔ 中性筒2", 2.0, 3.0),
    ("中性筒2 ↔ 中性筒3", 3.0, 4.0),
    ("中性筒3 ↔ 外壳", 4.0, 5.0),
]
for label, d_in, d_out in ring_names:
    r_in, r_out = d_in / 2, d_out / 2
    V = 3.14159265 * (r_out**2 - r_in**2) * INCH**2 * H_INCH * INCH / 1e6  # L
    pairs.append(V)
    w = (r_out - r_in) * INCH
    print(f"  {label:>22}({d_out:.0f}″) | {d_in:>5.1f}″ | {d_out:>5.1f}″ | {w:>6.1f} mm | {V:>7.3f} L")
print("  " + "-" * 74)
print(f"  {'合计水体积':>26} |         |         |           | {sum(pairs):>7.3f} L")
ok(f"五层同心结构、间距均匀（外壳内径 5″）时，总水体积 ≈ **{sum(pairs):.2f} L**")
print(f"""
  ★ 每个环隙的水体积**相同**（都是同宽 12.7 mm、同高 8″ 的环）——除了半径不同导致
     面积略增：内侧环 {pairs[0]:.3f} L，最外环 {pairs[-1]:.3f} L（差 {pairs[-1]/pairs[0]:.1f} 倍）

  ★ 注意：库内要求「水位只加到刚好与筒顶齐平」⇒ 实际水量 = 上表值（不再多）
""")

sec("Q5  层数 n 与电压分配（n 个中性筒把 12V 分成 n+1 段）")
print("""
  若外壳接 +12 V、中心阴极接 0 V（车身地），中间 n 个中性筒**不接电**：
  ⇒ 它们会被动地"浮"在电位上，把间隙分成 (n+1) 段
  ⇒ 每段**平均**电压降 = 12 / (n+1)  ⇒ 段数越多，每段电压越小
""")
print(f"  {'中性筒数 n':>10} | {'段数 n+1':>9} | {'每段平均压降':>12} | {'每段场强(0.5″间隙)':>18} | 备注")
print("  " + "-" * 78)
for n in range(1, 6):
    seg = n + 1
    dv = 12.0 / seg
    E = dv / (12.7e-3)          # V/m
    note = ""
    if n == 1: note = "库内允许的最少"
    elif n == 3: note = "★ 库内标准（3 个）"
    elif n >= 4: note = "老师说「性价比下降」"
    print(f"  {n:>10} | {seg:>9} | {dv:>9.2f} V | {E:>15.0f} V/m | {note}")
print("  " + "-" * 78)
ok("★ **层数 n 越多 ⇒ 段数越多 ⇒ 每段压降越小、场强越低**")
print("""
  ⇒ 这解释了老师那句「**层数越多性价比会下降**」：
     · 面积是线性增加的（Q3），但**每层分到的电压越来越小**；
     · 而要产生同样的产气/极化效果，可能需要更高总电压；
     · ⇒ 加层的收益递减。

  ⇒ 而「**性能可能更稳定**」也有对应：
     · 段数多 ⇒ 每段场强低 ⇒ **局部过电位小** ⇒ 点蚀/局部沸腾的倾向下降；
     · 但这也是**推测**，需要实验区分（见待办）。
""")

