# 库内 03 尺寸表（Mark III 标准）
LAYERS = [
    ("中心阴极（负极）", 1.0),
    ("中性筒 1", 2.0),
    ("中性筒 2", 3.0),
    ("中性筒 3", 4.0),
]
H_INCH = 8.0          # 筒高 8″
WALL_MM = 3.0         # 外壳壁厚 3mm

sec("Q1  五层同心圆：直径 / 半径 / 相邻间距")
print(f"""
  库内 03 尺寸表：中心阴极 1″、中性筒 2″/3″/4″、筒高 8″、外壳 3mm 厚壁
  换算：1″ = {INCH} mm
""")
print(f"  {'层':>18} | {'直径':>10} | {'半径':>10} | {'与内层半径差':>14}")
print("  " + "-" * 64)
prev_r = None
for name, d in LAYERS:
    r_mm = d * INCH / 2
    diff = "—" if prev_r is None else f"{r_mm - prev_r:.1f} mm = {(r_mm-prev_r)/INCH:.2f}″"
    print(f"  {name:>18} | {d:>7.1f}″ | {r_mm:>7.1f} mm | {diff:>14}")
    prev_r = r_mm
print("  " + "-" * 64)
ok("中性筒之间：半径差均为 **12.7 mm = 0.50″** ⇒ ★ **完全均匀**（与老师说的一致）")

sec("Q2  外壳内径该多大，才能「完全均匀」？")
r_last = 4.0 * INCH / 2
r_shell_uniform = r_last + 12.7
print(f"""
  最外中性筒半径 = {r_last:.1f} mm（4″/2）
  若要维持 0.5″ 间距 ⇒ 外壳内半径 = {r_last:.1f} + 12.7 = {r_shell_uniform:.1f} mm
                     ⇒ 外壳**内径** = {r_shell_uniform*2:.1f} mm = **{r_shell_uniform*2/INCH:.1f}″**
                     ⇒ 外壳**外径** = {r_shell_uniform*2 + 2*WALL_MM:.1f} mm ≈ {(r_shell_uniform*2+2*WALL_MM)/INCH:.2f}″
""")
ok(f"⇒ ★ **外壳内径 = 5.0″** 时，五层间距**完全均匀**（全是 0.5″）—— 这就是老师口述的那个版本")
warn("但库内 03 给的区间是「最外中性筒 → 外壳 = **0.5″–2″**」⇒ 允许更宽的外壳（内径 5″–7″）")
print(f"""
  ⇒ 两者的关系：
     · 外壳内径 5″ ⇒ 间距 0.5″（**老师口述版**，完全均匀）
     · 外壳内径 7″ ⇒ 间距 2.0″（库内允许的上限）
     两者不冲突：**老师的说法是库内区间的"下限/最紧凑"情形**。
""")

sec("Q3  各层浸水面积（等高 8″）")
print(f"""
  筒高 H = {H_INCH}″ = {H_INCH*INCH:.1f} mm
  单侧浸水面积 = π · D · H（圆柱侧面）
""")
print(f"  {'层':>18} | {'直径':>8} | {'单侧面积':>12} | {'双侧面积':>12}")
print("  " + "-" * 62)
total_single = 0.0
total_double = 0.0
for name, d in LAYERS:
    A1 = 3.14159265 * d * INCH * H_INCH * INCH / 1e6   # m²
    total_single += A1
    total_double += 2 * A1
    print(f"  {name:>18} | {d:>5.1f}″ | {A1*1e4:>9.1f} cm² | {2*A1*1e4:>9.1f} cm²")
print("  " + "-" * 62)
print(f"  {'合计':>18} |        | {total_single*1e4:>9.1f} cm² | {total_double*1e4:>9.1f} cm²")
