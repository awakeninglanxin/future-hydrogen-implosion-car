# -*- coding: utf-8 -*-
"""
_复算27 · Joe Cell 同心筒几何（老师口述结构 vs 库内 03 尺寸表）

老师 2026-09-13 口述结构：
  「cell 里装水，中心内管（负极）通常比中性管高一些，中性管代表处理管时不接正电，
   外体是接正极，处理好后中性管也会有电压分布，中性管至少 1 个、3 个更好，
   层数越多性价比会下降、性能可能更稳定。俯视都是同心圆，中间有 teflon 或尼龙
   绝缘物或天然橡胶，从内到外管间距均匀。」

要算五件事：
  Q1 五层同心圆的直径/半径/间距（核对「均匀」是否成立）
  Q2 外壳内径该是多少才能「完全均匀」？
  Q3 各层浸水面积（等高 8″）
  Q4 各层间环形水体积
  Q5 层数 n 与电压分配（n 个中性筒把 12V 分成 n+1 段）

纪律：凡数字必独立复算；库内口径与老师口径分开列。
零第三方依赖。
"""

INCH = 25.4

def sec(t):
    print("\n" + "=" * 74)
    print(t)
    print("=" * 74)

def ok(t):
    print("  [OK] " + t)

def warn(t):
    print("  [!]  " + t)

print("#" * 74)
print("#  _复算27 · Joe Cell 同心筒几何")
print("#" * 74)

# 库内 03 尺寸表（Mark III 标准）
LAYERS = [
    ("中心阴极（负极）", 1.0),
    ("中性筒 1", 2.0),
    ("中性筒 2", 3.0),
    ("中性筒 3", 4.0),
]
H_INCH = 8.0          # 筒高 8″
WALL_MM = 3.0         # 外壳壁厚 3mm

sec("Q1  五层同心圆：直径 / 半径 / 相邻间距")
print(f"""
  库内 03 尺寸表：中心阴极 1″、中性筒 2″/3″/4″、筒高 8″、外壳 3mm 厚壁
  换算：1″ = {INCH} mm
""")
print(f"  {'层':>18} | {'直径':>10} | {'半径':>10} | {'与内层半径差':>14}")
print("  " + "-" * 64)
prev_r = None
for name, d in LAYERS:
    r_mm = d * INCH / 2
    diff = "—" if prev_r is None else f"{r_mm - prev_r:.1f} mm = {(r_mm-prev_r)/INCH:.2f}″"
    print(f"  {name:>18} | {d:>7.1f}″ | {r_mm:>7.1f} mm | {diff:>14}")
    prev_r = r_mm
print("  " + "-" * 64)
ok("中性筒之间：半径差均为 **12.7 mm = 0.50″** ⇒ ★ **完全均匀**（与老师说的一致）")

sec("Q2  外壳内径该多大，才能「完全均匀」？")
r_last = 4.0 * INCH / 2
r_shell_uniform = r_last + 12.7
print(f"""
  最外中性筒半径 = {r_last:.1f} mm（4″/2）
  若要维持 0.5″ 间距 ⇒ 外壳内半径 = {r_last:.1f} + 12.7 = {r_shell_uniform:.1f} mm
                     ⇒ 外壳**内径** = {r_shell_uniform*2:.1f} mm = **{r_shell_uniform*2/INCH:.1f}″**
                     ⇒ 外壳**外径** = {r_shell_uniform*2 + 2*WALL_MM:.1f} mm ≈ {(r_shell_uniform*2+2*WALL_MM)/INCH:.2f}″
""")
ok(f"⇒ ★ **外壳内径 = 5.0″** 时，五层间距**完全均匀**（全是 0.5″）—— 这就是老师口述的那个版本")
warn("但库内 03 给的区间是「最外中性筒 → 外壳 = **0.5″–2″**」⇒ 允许更宽的外壳（内径 5″–7″）")
print(f"""
  ⇒ 两者的关系：
     · 外壳内径 5″ ⇒ 间距 0.5″（**老师口述版**，完全均匀）
     · 外壳内径 7″ ⇒ 间距 2.0″（库内允许的上限）
     两者不冲突：**老师的说法是库内区间的"下限/最紧凑"情形**。
""")

sec("Q3  各层浸水面积（等高 8″）")
print(f"""
  筒高 H = {H_INCH}″ = {H_INCH*INCH:.1f} mm
  单侧浸水面积 = π · D · H（圆柱侧面）
""")
print(f"  {'层':>18} | {'直径':>8} | {'单侧面积':>12} | {'双侧面积':>12}")
print("  " + "-" * 62)
total_single = 0.0
total_double = 0.0
for name, d in LAYERS:
    A1 = 3.14159265 * d * INCH * H_INCH * INCH / 1e6   # m²
    total_single += A1
    total_double += 2 * A1
    print(f"  {name:>18} | {d:>5.1f}″ | {A1*1e4:>9.1f} cm² | {2*A1*1e4:>9.1f} cm²")
print("  " + "-" * 62)
print(f"  {'合计':>18} |        | {total_single*1e4:>9.1f} cm² | {total_double*1e4:>9.1f} cm²")
ok(f"四层筒的双侧总浸水面积 ≈ **{total_double*1e4:.0f} cm²**（约 {total_double:.4f} m²）")
print("""
  ★ 关键：**中性筒是"两侧都有水"的**（它们浮在环形水格里），
     所以增加中性筒层数 ⇒ **面积近似线性增加**（每多一层，多一圈圆柱的两侧）
""")

sec("Q4  各层间环形水体积")
print(f"  环形体积 V = π(R_out² − R_in²) · H     （1 L = 1e6 mm³）")
print(f"  {'环隙':>26} | {'内径':>7} | {'外径':>7} | {'宽度':>9} | {'水体积':>10}")
print("  " + "-" * 74)
pairs = []
ring_names = [
    ("阴极 ↔ 中性筒1", 1.0, 2.0),
    ("中性筒1 ↔ 中性筒2", 2.0, 3.0),
    ("中性筒2 ↔ 中性筒3", 3.0, 4.0),
    ("中性筒3 ↔ 外壳", 4.0, 5.0),
]
for label, d_in, d_out in ring_names:
    r_in, r_out = d_in / 2, d_out / 2
    V = 3.14159265 * (r_out**2 - r_in**2) * INCH**2 * H_INCH * INCH / 1e6  # L
    pairs.append(V)
    w = (r_out - r_in) * INCH
    print(f"  {label:>22}({d_out:.0f}″) | {d_in:>5.1f}″ | {d_out:>5.1f}″ | {w:>6.1f} mm | {V:>7.3f} L")
print("  " + "-" * 74)
print(f"  {'合计水体积':>26} |         |         |           | {sum(pairs):>7.3f} L")
ok(f"五层同心结构、间距均匀（外壳内径 5″）时，总水体积 ≈ **{sum(pairs):.2f} L**")
print(f"""
  ★ 每个环隙的水体积**相同**（都是同宽 12.7 mm、同高 8″ 的环）——除了半径不同导致
     面积略增：内侧环 {pairs[0]:.3f} L，最外环 {pairs[-1]:.3f} L（差 {pairs[-1]/pairs[0]:.1f} 倍）

  ★ 注意：库内要求「水位只加到刚好与筒顶齐平」⇒ 实际水量 = 上表值（不再多）
""")

sec("Q5  层数 n 与电压分配（n 个中性筒把 12V 分成 n+1 段）")
print("""
  若外壳接 +12 V、中心阴极接 0 V（车身地），中间 n 个中性筒**不接电**：
  ⇒ 它们会被动地"浮"在电位上，把间隙分成 (n+1) 段
  ⇒ 每段**平均**电压降 = 12 / (n+1)  ⇒ 段数越多，每段电压越小
""")
print(f"  {'中性筒数 n':>10} | {'段数 n+1':>9} | {'每段平均压降':>12} | {'每段场强(0.5″间隙)':>18} | 备注")
print("  " + "-" * 78)
for n in range(1, 6):
    seg = n + 1
    dv = 12.0 / seg
    E = dv / (12.7e-3)          # V/m
    note = ""
    if n == 1: note = "库内允许的最少"
    elif n == 3: note = "★ 库内标准（3 个）"
    elif n >= 4: note = "老师说「性价比下降」"
    print(f"  {n:>10} | {seg:>9} | {dv:>9.2f} V | {E:>15.0f} V/m | {note}")
print("  " + "-" * 78)
ok("★ **层数 n 越多 ⇒ 段数越多 ⇒ 每段压降越小、场强越低**")
print("""
  ⇒ 这解释了老师那句「**层数越多性价比会下降**」：
     · 面积是线性增加的（Q3），但**每层分到的电压越来越小**；
     · 而要产生同样的产气/极化效果，可能需要更高总电压；
     · ⇒ 加层的收益递减。

  ⇒ 而「**性能可能更稳定**」也有对应：
     · 段数多 ⇒ 每段场强低 ⇒ **局部过电位小** ⇒ 点蚀/局部沸腾的倾向下降；
     · 但这也是**推测**，需要实验区分（见待办）。
""")

sec("汇总")
print(f"""
  项目                                       结果
  --------------------------------------------------------------------------------
  相邻中性筒半径差                            12.7 mm = 0.50″（均匀）
  「完全均匀」所需外壳内径                      **5.0″**（外径 ≈ 5.24″）
  库内允许的外壳间距区间                        0.5″ – 2.0″（⇒ 外壳内径 5″ – 7″）
  四层筒双侧总浸水面积                          ≈ {total_double*1e4:.0f} cm²
  总水体积（筒高8″、外壳内径5″）                 ≈ {sum(pairs):.2f} L
  12V 分段（n=3）                             4 段 × 3 V = 12 V

  ★★★ 一句话：
     老师口述的结构与库内 03 尺寸表**基本一致**，
     且「从内到外间距均匀」= **外壳内径 5″** 的配置（库内区间的下限）。
     ⇒ 两处**需要确认**的差异只有：
        ① 中心阴极是否比中性筒高（库内写「完全相同 / 严格齐平」）
        ② 绝缘物材质（库内写「实验室纯胶塞」，老师说 teflon/尼龙/天然橡胶）
""")

print("#" * 74)
print("#  复算完毕")
print("#" * 74)
