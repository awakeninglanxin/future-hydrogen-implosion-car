    R_free = 0.33
    delta = L**2 / (8 * R_free)
    print(f"  {p_kpa:>6} kPa | {A*1e4:>9.0f} cm² | {L*1000:>6.0f} × {w_tire*1000:.0f} mm | "
          f"{delta*1000:>9.1f} mm | {label}")
